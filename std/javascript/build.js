// The JavaScript runtime is the single executable source for JS and TS.
// Export names are read from std.js so the declaration list cannot drift.
const fs = require('node:fs');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname, 'std.js'), 'utf8');
const block = source.match(/module\.exports\s*=\s*\{([\s\S]*?)\};/);
if (!block) throw new Error('runtime exports not found');
const names = block[1].replace(/\/\/[^\n]*/g, '').split(',').map(s => s.trim()).filter(Boolean);
if (new Set(names).size !== names.length) throw new Error('duplicate runtime export');
const special = {
  unmarshalUint: '(n: number, b: Uint8Array): [number, bigint]',
  unmarshalInt: '(n: number, b: Uint8Array): [number, bigint]',
  sizeUint: '(v: number | bigint): number',
  sizeInt: '(v: number | bigint): number',
  marshalUint: '(n: number, b: Uint8Array, v: number | bigint): number',
  marshalInt: '(n: number, b: Uint8Array, v: number | bigint): number',
  unmarshalBool: '(n: number, b: Uint8Array): [number, boolean]',
  unmarshalString: '(n: number, b: Uint8Array): [number, string]',
  unmarshalTime: '(n: number, b: Uint8Array): [number, Time]',
  marshalTime: '(n: number, b: Uint8Array, value: Date | Time): number',
};
const lines = ['// Generated by std/javascript/build.js from the shared runtime exports.',
  'export class BencError extends Error {}',
  'export const ErrOverflow: BencError;', 'export const ErrBufTooSmall: BencError;',
  'export const ErrInvalidData: BencError;',
  'export class Time extends Date { constructor(unixNano?: number | bigint); unixNano: bigint; toDate(): Date; }'];
for (const name of names) {
  if (['BencError', 'ErrOverflow', 'ErrBufTooSmall', 'ErrInvalidData', 'Time'].includes(name)) continue;
  if (!new RegExp(`\\b(?:function|const)\\s+${name}\\b`).test(source) &&
      !new RegExp(`\\b(?:skip|size|marshal|unmarshal):\\s*${name}\\b`).test(source))
    throw new Error(`unknown runtime export: ${name}`);
  const signature = special[name] || (name.startsWith('unmarshal') ? '(n: number, b: Uint8Array, ...args: any[]): [number, any]' :
    name.startsWith('marshal') ? '(n: number, b: Uint8Array, ...args: any[]): number' :
    name.startsWith('skip') ? '(n: number, b: Uint8Array, ...args: any[]): number' :
    '(...args: any[]): number');
  lines.push(`export function ${name}${signature};`);
}
const declarations = lines.join('\n') + '\n';
for (const [file, contents] of [
  [path.join(__dirname, 'std.d.ts'), declarations],
]) {
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== contents)
      throw new Error(`${file} is stale; run npm run build`);
  } else fs.writeFileSync(file, contents);
}
