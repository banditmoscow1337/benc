package rust

import (
	"bytes"
	"fmt"
	"go/ast"
	"strings"

	"github.com/banditmoscow1337/benc/cmd/generator/common"
)

type generator struct {
	*common.Context
	out bytes.Buffer
}

func New(ctx *common.Context) common.Generator          { return &generator{Context: ctx} }
func (g *generator) printf(pattern string, args ...any) { fmt.Fprintf(&g.out, pattern, args...) }

func (g *generator) Generate() error {
	if err := g.Validate(); err != nil {
		return err
	}
	g.out.Reset()
	g.printf("// Code generated by benc generator; DO NOT EDIT.\nuse std::collections::HashMap;\n\n")
	for _, ts := range g.OrderedTypes() {
		name := ts.Name.Name
		if m, ok := ts.Type.(*ast.MapType); ok {
			g.printf("#[derive(Debug, Clone, PartialEq, Default)]\npub struct %s(pub %s); // %s\n", name, g.rustType(m), g.ExprToString(m))
			g.printf("impl %s {\n    pub fn size(&self) -> usize { %s }\n", name, g.sizeExpr(m, "&self.0"))
			g.printf("    pub fn marshal(&self, writer: &mut &mut [u8]) -> benc::Result<()> { %s }\n", g.writeExpr(m, "&self.0", "writer"))
			g.printf("    pub fn unmarshal(reader: &mut &[u8]) -> benc::Result<Self> { let mut cursor = *reader; let v = Self(%s?); *reader = cursor; Ok(v) }\n}\n\n", g.readExpr(m, "&mut cursor"))
			continue
		}
		g.printf("#[derive(Debug, Clone, PartialEq)]\npub struct %s {\n", name)
		for _, f := range g.GetSupportedFields(ts) {
			for _, id := range f.Names {
				g.printf("    pub %s: %s, // %s\n", id.Name, g.rustType(f.Type), g.ExprToString(f.Type))
			}
		}
		g.printf("}\nimpl Default for %s { fn default() -> Self { Self {\n", name)
		for _, f := range g.GetSupportedFields(ts) {
			for _, id := range f.Names {
				g.printf("    %s: %s,\n", id.Name, g.defaultExpr(f.Type))
			}
		}
		g.printf("} } }\nimpl %s {\n    pub fn size(&self) -> usize {\n        let mut size = 0;\n", name)
		for _, f := range g.GetSupportedFields(ts) {
			for _, id := range f.Names {
				g.printf("        size += %s;\n", g.sizeExpr(f.Type, "&self."+id.Name))
			}
		}
		g.printf("        size\n    }\n    pub fn marshal(&self, writer: &mut &mut [u8]) -> benc::Result<()> {\n")
		for _, f := range g.GetSupportedFields(ts) {
			for _, id := range f.Names {
				g.printf("        %s?;\n", g.writeExpr(f.Type, "&self."+id.Name, "writer"))
			}
		}
		g.printf("        Ok(())\n    }\n    pub fn unmarshal(reader: &mut &[u8]) -> benc::Result<Self> {\n        let mut cursor = *reader;\n        let value = Self {\n")
		for _, f := range g.GetSupportedFields(ts) {
			for _, id := range f.Names {
				g.printf("            %s: %s?,\n", id.Name, g.readExpr(f.Type, "&mut cursor"))
			}
		}
		g.printf("        };\n        *reader = cursor;\n        Ok(value)\n    }\n}\n\n")
	}
	return g.WriteFile(&g.out, "_benc", "rs")
}

func (g *generator) Tests() error {
	g.out.Reset()
	g.printf("// Code generated by benc generator; DO NOT EDIT.\nmod model { include!(\"%s_benc.rs\"); }\nfn main() {\n", g.BaseName)
	for _, ts := range g.Types {
		name := ts.Name.Name
		g.printf("    { let value = model::%s::default(); let mut buf = vec![0u8; value.size()]; { let mut writer = buf.as_mut_slice(); value.marshal(&mut writer).unwrap(); assert!(writer.is_empty()); } let mut reader = buf.as_slice(); let copy = model::%s::unmarshal(&mut reader).unwrap(); assert!(reader.is_empty()); assert_eq!(copy, value); }\n", name, name)
	}
	g.printf("}\n")
	return g.WriteFile(&g.out, "_benc_test", "rs")
}

func rustByte(e ast.Expr) bool {
	id, ok := e.(*ast.Ident)
	return ok && (id.Name == "byte" || id.Name == "uint8")
}
func (g *generator) rustType(e ast.Expr) string {
	switch t := e.(type) {
	case *ast.Ident:
		switch t.Name {
		case "string":
			return "String"
		case "bool":
			return "bool"
		case "int":
			return "isize"
		case "uint":
			return "usize"
		case "byte":
			return "u8"
		case "rune":
			return "i32"
		case "int8", "int16", "int32", "int64", "uint8", "uint16", "uint32", "uint64", "float32", "float64":
			return strings.NewReplacer("uint", "u", "int", "i", "float", "f").Replace(t.Name)
		default:
			return t.Name
		}
	case *ast.SelectorExpr:
		return "chrono::DateTime<chrono::Utc>"
	case *ast.StarExpr:
		return "Option<" + g.rustType(t.X) + ">"
	case *ast.ArrayType:
		if t.Len != nil {
			return fmt.Sprintf("[%s; %s]", g.rustType(t.Elt), g.ExprToString(t.Len))
		}
		return "Vec<" + g.rustType(t.Elt) + ">"
	case *ast.MapType:
		return "HashMap<" + g.rustType(t.Key) + ", " + g.rustType(t.Value) + ">"
	}
	return "()"
}
func (g *generator) defaultExpr(e ast.Expr) string {
	switch t := e.(type) {
	case *ast.Ident:
		switch t.Name {
		case "string":
			return "String::new()"
		case "bool":
			return "false"
		case "float32", "float64":
			return "0.0"
		case "byte", "rune", "int", "uint", "int8", "uint8", "int16", "uint16", "int32", "uint32", "int64", "uint64":
			return "0"
		default:
			return t.Name + "::default()"
		}
	case *ast.StarExpr:
		return "None"
	case *ast.ArrayType:
		if t.Len != nil {
			return "std::array::from_fn(|_| " + g.defaultExpr(t.Elt) + ")"
		}
		return "Vec::new()"
	case *ast.MapType:
		return "HashMap::new()"
	case *ast.SelectorExpr:
		return "chrono::DateTime::from_timestamp_nanos(0)"
	}
	return "Default::default()"
}
func (g *generator) rustName(name string) string {
	switch name {
	case "byte", "uint8":
		return "u8"
	case "rune":
		return "i32"
	case "int":
		return "isize"
	case "uint":
		return "usize"
	case "string":
		return "string"
	default:
		return strings.NewReplacer("uint", "u", "int", "i", "float", "f").Replace(name)
	}
}
func (g *generator) sizeExpr(e ast.Expr, v string) string {
	switch t := e.(type) {
	case *ast.Ident:
		if _, ok := g.TypeSpecs[t.Name]; ok {
			return "(" + v + ").size()"
		}
		if t.Name == "int" || t.Name == "uint" {
			return fmt.Sprintf("benc::size_%s(*%s)", g.rustName(t.Name), v)
		}
		if t.Name == "string" {
			return fmt.Sprintf("benc::size_string(%s)", v)
		}
		return fmt.Sprintf("benc::size_%s()", g.rustName(t.Name))
	case *ast.SelectorExpr:
		return "benc::size_time()"
	case *ast.StarExpr:
		return fmt.Sprintf("benc::size_option(%s, |v| %s)", v, g.sizeExpr(t.X, "v"))
	case *ast.ArrayType:
		if t.Len != nil {
			return fmt.Sprintf("(%s).iter().map(|v| %s).sum::<usize>()", v, g.sizeExpr(t.Elt, "v"))
		}
		if rustByte(t.Elt) {
			return fmt.Sprintf("benc::size_bytes(%s)", v)
		}
		return fmt.Sprintf("benc::size_slice(%s, |v| %s)", v, g.sizeExpr(t.Elt, "v"))
	case *ast.MapType:
		return fmt.Sprintf("benc::size_map(%s, |v| %s, |v| %s)", v, g.sizeExpr(t.Key, "v"), g.sizeExpr(t.Value, "v"))
	}
	return "0"
}
func (g *generator) writeExpr(e ast.Expr, v, w string) string {
	switch t := e.(type) {
	case *ast.Ident:
		if _, ok := g.TypeSpecs[t.Name]; ok {
			return fmt.Sprintf("(%s).marshal(%s)", v, w)
		}
		if t.Name == "string" {
			return fmt.Sprintf("benc::marshal_string(%s, %s)", v, w)
		}
		return fmt.Sprintf("benc::marshal_%s(*%s, %s)", g.rustName(t.Name), v, w)
	case *ast.SelectorExpr:
		return fmt.Sprintf("benc::marshal_time((*(%s)).clone(), %s)", v, w)
	case *ast.StarExpr:
		return fmt.Sprintf("benc::marshal_option(%s, %s, |v, w| %s)", v, w, g.writeExpr(t.X, "v", "w"))
	case *ast.ArrayType:
		if t.Len != nil {
			return fmt.Sprintf("{ for v in (%s).iter() { %s?; } Ok::<(), benc::Error>(()) }", v, g.writeExpr(t.Elt, "v", w))
		}
		if rustByte(t.Elt) {
			return fmt.Sprintf("benc::marshal_bytes(%s, %s)", v, w)
		}
		return fmt.Sprintf("benc::marshal_slice(%s, %s, |v, w| %s)", v, w, g.writeExpr(t.Elt, "v", "w"))
	case *ast.MapType:
		return fmt.Sprintf("benc::marshal_map(%s, %s, |v, w| %s, |v, w| %s)", v, w, g.writeExpr(t.Key, "v", "w"), g.writeExpr(t.Value, "v", "w"))
	}
	return "Ok(())"
}
func (g *generator) readExpr(e ast.Expr, r string) string {
	switch t := e.(type) {
	case *ast.Ident:
		if _, ok := g.TypeSpecs[t.Name]; ok {
			return fmt.Sprintf("%s::unmarshal(%s)", t.Name, r)
		}
		if t.Name == "string" {
			return fmt.Sprintf("benc::unmarshal_string(%s).map(String::from)", r)
		}
		return fmt.Sprintf("benc::unmarshal_%s(%s)", g.rustName(t.Name), r)
	case *ast.SelectorExpr:
		return fmt.Sprintf("benc::unmarshal_time(%s)", r)
	case *ast.StarExpr:
		return fmt.Sprintf("benc::unmarshal_option(%s, |r| %s)", r, g.readExpr(t.X, "r"))
	case *ast.ArrayType:
		if t.Len != nil {
			return fmt.Sprintf("{ let mut values = Vec::new(); for _ in 0..%s { values.push(%s?); } values.try_into().map_err(|_| benc::Error::OutOfRange) }", g.ExprToString(t.Len), g.readExpr(t.Elt, r))
		}
		if rustByte(t.Elt) {
			return fmt.Sprintf("benc::unmarshal_bytes_copied(%s)", r)
		}
		return fmt.Sprintf("benc::unmarshal_slice(%s, |r| %s)", r, g.readExpr(t.Elt, "r"))
	case *ast.MapType:
		return fmt.Sprintf("benc::unmarshal_map(%s, |r| %s, |r| %s)", r, g.readExpr(t.Key, "r"), g.readExpr(t.Value, "r"))
	}
	return "Ok(Default::default())"
}
