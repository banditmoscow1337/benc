package csharp

import (
	"bytes"
	"fmt"
	"go/ast"
	"strings"

	"github.com/banditmoscow1337/benc/cmd/generator/common"
)

type generator struct {
	*common.Context
	out bytes.Buffer
}

func New(ctx *common.Context) common.Generator { return &generator{Context: ctx} }
func (g *generator) printf(s string, a ...any) { fmt.Fprintf(&g.out, s, a...) }

func (g *generator) Generate() error {
	if err := g.Validate(); err != nil {
		return err
	}
	g.out.Reset()
	g.printf(`// Code generated by benc generator; DO NOT EDIT.
#nullable enable
using System;
using System.Collections.Generic;
using System.Linq;
using Bstd;

internal static class BencFixed { // benc:internal
  public static int SizeBytes(byte[] v, int count) { if (v.Length != count) throw new ArgumentException("fixed length"); return count; }
  public static void WriteBytes(ref Span<byte> b, byte[] v, int count) {
    SizeBytes(v, count); if (b.Length < count) throw new BstdBufferTooSmallException(); v.AsSpan().CopyTo(b); b = b.Slice(count);
  }
  public static byte[] ReadBytes(ref ReadOnlySpan<byte> b, int count) {
    if (b.Length < count) throw new BstdBufferTooSmallException(); var value = b.Slice(0,count).ToArray(); b = b.Slice(count); return value;
  }
  public static int Size<T>(ICollection<T> v, int count, GetSizeDelegate<T> fn) {
    if (v.Count != count) throw new ArgumentException("fixed length"); return v.Sum(item => fn(item));
  }
  public static void Write<T>(ref Span<byte> b, ICollection<T> v, int count, WriteElementDelegate<T> fn) {
    if (v.Count != count) throw new ArgumentException("fixed length"); foreach (var item in v) fn(ref b, item);
  }
  public static List<T> Read<T>(ref ReadOnlySpan<byte> b, int count, ReadElementDelegate<T> fn) {
    var values = new List<T>(); for (int i=0;i<count;i++) values.Add(fn(ref b)); return values;
  }
}

`)
	for _, ts := range g.OrderedTypes() {
		name := ts.Name.Name
		if m, ok := ts.Type.(*ast.MapType); ok {
			g.printf("public class %s { // benc:type %s\n", name, g.ExprToString(m))
			g.printf("  public Dictionary<%s, %s> Value = new();\n", g.typ(m.Key), g.typ(m.Value))
			g.printf("  public int Size() => %s;\n", g.size(m, "Value"))
			g.printf("  public void Marshal(ref Span<byte> b) { %s }\n", g.write(m, "b", "Value"))
			g.printf("  public static %s Unmarshal(ref ReadOnlySpan<byte> b) { var result = new %s(); result.Value = %s; return result; }\n}\n\n", name, name, g.read(m, "b"))
			continue
		}
		g.printf("public class %s {\n", name)
		for _, f := range g.GetSupportedFields(ts) {
			for _, id := range f.Names {
				g.printf("  public %s %s = %s; // %s\n", g.typ(f.Type), id.Name, g.def(f.Type), g.ExprToString(f.Type))
			}
		}
		g.printf("  public int Size() { int size = 0;\n")
		for _, f := range g.GetSupportedFields(ts) {
			for _, id := range f.Names {
				g.printf("    size += %s;\n", g.size(f.Type, "this."+id.Name))
			}
		}
		g.printf("    return size; }\n  public void Marshal(ref Span<byte> b) {\n")
		for _, f := range g.GetSupportedFields(ts) {
			for _, id := range f.Names {
				g.printf("    %s\n", g.write(f.Type, "b", "this."+id.Name))
			}
		}
		g.printf("  }\n  public static %s Unmarshal(ref ReadOnlySpan<byte> b) { var value = new %s();\n", name, name)
		for _, f := range g.GetSupportedFields(ts) {
			for _, id := range f.Names {
				g.printf("    value.%s = %s;\n", id.Name, g.read(f.Type, "b"))
			}
		}
		g.printf("    return value; }\n}\n\n")
	}
	return g.WriteFile(&g.out, "_benc", "cs")
}
func (g *generator) Tests() error {
	g.out.Reset()
	g.printf("// Code generated by benc generator; DO NOT EDIT.\nusing System;\nusing System.Linq;\npublic static class BencGeneratedTest { public static void Main() {\n")
	for _, ts := range g.Types {
		n := ts.Name.Name
		g.printf("  { var value = new %s(); byte[] wire = new byte[value.Size()]; Span<byte> writer = wire; value.Marshal(ref writer); if (!writer.IsEmpty) throw new Exception(\"encode\"); ReadOnlySpan<byte> reader = wire; var copy = %s.Unmarshal(ref reader); if (!reader.IsEmpty) throw new Exception(\"decode\"); byte[] again = new byte[copy.Size()]; Span<byte> second = again; copy.Marshal(ref second); if (!second.IsEmpty || !wire.SequenceEqual(again)) throw new Exception(\"roundtrip\"); }\n", n, n)
	}
	g.printf("} }\n")
	return g.WriteFile(&g.out, "_benc_test", "cs")
}
func isByte(e ast.Expr) bool {
	t, ok := e.(*ast.Ident)
	return ok && (t.Name == "byte" || t.Name == "uint8")
}
func (g *generator) typ(e ast.Expr) string {
	switch t := e.(type) {
	case *ast.Ident:
		m := map[string]string{"string": "string", "bool": "bool", "byte": "byte", "rune": "int", "int": "nint", "uint": "nuint", "int8": "sbyte", "uint8": "byte", "int16": "short", "uint16": "ushort", "int32": "int", "uint32": "uint", "int64": "long", "uint64": "ulong", "float32": "float", "float64": "double"}
		if v, ok := m[t.Name]; ok {
			return v
		}
		return t.Name
	case *ast.SelectorExpr:
		return "long" // exact nanoseconds; DateTime cannot represent sub-tick values
	case *ast.StarExpr:
		return g.typ(t.X) + "?"
	case *ast.ArrayType:
		if isByte(t.Elt) {
			return "byte[]"
		}
		return "List<" + g.typ(t.Elt) + ">"
	case *ast.MapType:
		return "Dictionary<" + g.typ(t.Key) + ", " + g.typ(t.Value) + ">"
	}
	return "object"
}
func (g *generator) def(e ast.Expr) string {
	switch t := e.(type) {
	case *ast.Ident:
		switch t.Name {
		case "string":
			return `""`
		case "bool":
			return "false"
		case "float32":
			return "0f"
		case "float64":
			return "0d"
		case "int", "uint", "byte", "rune", "int8", "uint8", "int16", "uint16", "int32", "uint32", "int64", "uint64":
			return "0"
		default:
			return "new " + t.Name + "()"
		}
	case *ast.SelectorExpr:
		return "0L"
	case *ast.StarExpr:
		return "null"
	case *ast.ArrayType:
		if isByte(t.Elt) {
			if t.Len != nil {
				return "new byte[" + g.ExprToString(t.Len) + "]"
			}
			return "Array.Empty<byte>()"
		}
		if t.Len != nil {
			return "Enumerable.Range(0, " + g.ExprToString(t.Len) + ").Select(_ => " + g.def(t.Elt) + ").ToList()"
		}
		return "new List<" + g.typ(t.Elt) + ">()"
	case *ast.MapType:
		return "new Dictionary<" + g.typ(t.Key) + ", " + g.typ(t.Value) + ">()"
	}
	return "default!"
}
func csMethod(s string) string {
	switch s {
	case "byte", "uint8":
		return "Byte"
	case "int8":
		return "SByte"
	case "float32":
		return "Single"
	case "float64":
		return "Double"
	case "rune":
		return "Int32"
	case "int", "uint":
		return "Varint"
	default:
		return strings.ToUpper(s[:1]) + s[1:]
	}
}
func (g *generator) size(e ast.Expr, v string) string {
	switch t := e.(type) {
	case *ast.Ident:
		if _, ok := g.TypeSpecs[t.Name]; ok {
			return v + ".Size()"
		}
		if t.Name == "string" {
			return "BstdSerializer.GetSizeString(" + v + ")"
		}
		if t.Name == "int" || t.Name == "uint" {
			return "BstdSerializer.GetSizeVarint(" + v + ")"
		}
		return "BstdSerializer.GetSize" + csMethod(t.Name) + "()"
	case *ast.SelectorExpr:
		return "BstdSerializer.GetSizeTime()"
	case *ast.StarExpr:
		kind := "Struct"
		if g.reference(t.X) {
			kind = "Class"
		}
		return "BstdSerializer.GetSizePointer" + kind + "(" + v + ", item => " + g.size(t.X, "item") + ")"
	case *ast.ArrayType:
		if t.Len != nil {
			if isByte(t.Elt) {
				return "BencFixed.SizeBytes(" + v + ", " + g.ExprToString(t.Len) + ")"
			}
			return "BencFixed.Size(" + v + ", " + g.ExprToString(t.Len) + ", item => " + g.size(t.Elt, "item") + ")"
		}
		if isByte(t.Elt) {
			return "BstdSerializer.GetSizeBytes(" + v + ")"
		}
		return "BstdSerializer.GetSizeArray(" + v + ", item => " + g.size(t.Elt, "item") + ")"
	case *ast.MapType:
		return "BstdSerializer.GetSizeDictionary(" + v + ", key => " + g.size(t.Key, "key") + ", item => " + g.size(t.Value, "item") + ")"
	}
	return "0"
}
func (g *generator) reference(e ast.Expr) bool {
	switch t := e.(type) {
	case *ast.ArrayType, *ast.MapType:
		return true
	case *ast.Ident:
		if t.Name == "string" {
			return true
		}
		_, ok := g.TypeSpecs[t.Name]
		return ok
	}
	return false
}
func (g *generator) write(e ast.Expr, b, v string) string {
	switch t := e.(type) {
	case *ast.Ident:
		if _, ok := g.TypeSpecs[t.Name]; ok {
			return v + ".Marshal(ref " + b + ");"
		}
		method := csMethod(t.Name)
		if t.Name == "int" || t.Name == "uint" {
			method = "Varint"
		}
		return "BstdSerializer.Write" + method + "(ref " + b + ", " + v + ");"
	case *ast.SelectorExpr:
		return "BstdSerializer.WriteTimeNanos(ref " + b + ", " + v + ");"
	case *ast.StarExpr:
		kind := "Struct"
		if g.reference(t.X) {
			kind = "Class"
		}
		return "BstdSerializer.WritePointer" + kind + "(ref " + b + ", " + v + ", (ref Span<byte> buf, " + g.typ(t.X) + " item) => { " + g.write(t.X, "buf", "item") + " });"
	case *ast.ArrayType:
		if t.Len != nil {
			if isByte(t.Elt) {
				return "BencFixed.WriteBytes(ref " + b + ", " + v + ", " + g.ExprToString(t.Len) + ");"
			}
			return "BencFixed.Write(ref " + b + ", " + v + ", " + g.ExprToString(t.Len) + ", (ref Span<byte> buf, " + g.typ(t.Elt) + " item) => { " + g.write(t.Elt, "buf", "item") + " });"
		}
		if isByte(t.Elt) {
			return "BstdSerializer.WriteBytes(ref " + b + ", " + v + ");"
		}
		return "BstdSerializer.WriteArray(ref " + b + ", " + v + ", (ref Span<byte> buf, " + g.typ(t.Elt) + " item) => { " + g.write(t.Elt, "buf", "item") + " });"
	case *ast.MapType:
		return "BstdSerializer.WriteDictionary(ref " + b + ", " + v + ", (ref Span<byte> buf, " + g.typ(t.Key) + " key) => { " + g.write(t.Key, "buf", "key") + " }, (ref Span<byte> buf, " + g.typ(t.Value) + " item) => { " + g.write(t.Value, "buf", "item") + " });"
	}
	return ""
}
func (g *generator) read(e ast.Expr, b string) string {
	switch t := e.(type) {
	case *ast.Ident:
		if _, ok := g.TypeSpecs[t.Name]; ok {
			return t.Name + ".Unmarshal(ref " + b + ")"
		}
		method := csMethod(t.Name)
		if t.Name == "int" {
			method = "SignedVarint"
		}
		if t.Name == "uint" {
			method = "Varint"
		}
		return "BstdSerializer.Read" + method + "(ref " + b + ")"
	case *ast.SelectorExpr:
		return "BstdSerializer.ReadTimeNanos(ref " + b + ")"
	case *ast.StarExpr:
		kind := "Struct"
		if g.reference(t.X) {
			kind = "Class"
		}
		return "BstdSerializer.ReadPointer" + kind + "(ref " + b + ", (ref ReadOnlySpan<byte> buf) => " + g.read(t.X, "buf") + ")"
	case *ast.ArrayType:
		if t.Len != nil {
			if isByte(t.Elt) {
				return "BencFixed.ReadBytes(ref " + b + ", " + g.ExprToString(t.Len) + ")"
			}
			return "BencFixed.Read(ref " + b + ", " + g.ExprToString(t.Len) + ", (ref ReadOnlySpan<byte> buf) => " + g.read(t.Elt, "buf") + ")"
		}
		if isByte(t.Elt) {
			return "BstdSerializer.ReadBytesCopied(ref " + b + ")"
		}
		return "BstdSerializer.ReadArray(ref " + b + ", (ref ReadOnlySpan<byte> buf) => " + g.read(t.Elt, "buf") + ").ToList()"
	case *ast.MapType:
		return "BstdSerializer.ReadDictionary(ref " + b + ", (ref ReadOnlySpan<byte> buf) => " + g.read(t.Key, "buf") + ", (ref ReadOnlySpan<byte> buf) => " + g.read(t.Value, "buf") + ")"
	}
	return "default!"
}
