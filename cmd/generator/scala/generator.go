func (g *generator) Tests() error {
	g.out.Reset()
	g.printf("// Code generated by benc generator; DO NOT EDIT.\nobject BencGeneratedTest:\n  def main(args: Array[String]): Unit =\n")
	for _, ts := range g.Types {
		n := ts.Name.Name
		g.printf("    val value%s = %s()\n    val wire%s = new Array[Byte](%s.codec.size(value%s))\n    assert(%s.codec.write(0,wire%s,value%s) == wire%s.length)\n    val copy%s = %s.codec.read(0,wire%s).toOption.get\n    assert(copy%s._1 == wire%s.length)\n    val again%s = new Array[Byte](%s.codec.size(copy%s._2))\n    assert(%s.codec.write(0,again%s,copy%s._2) == again%s.length && wire%s.sameElements(again%s))\n", n, n, n, n, n, n, n, n, n, n, n, n, n, n, n, n, n, n, n, n, n, n, n)
	}
	return g.WriteFile(&g.out, "_benc_test", "scala")
}
func isByte(e ast.Expr) bool {
	t, ok := e.(*ast.Ident)
	return ok && (t.Name == "byte" || t.Name == "uint8")
}
func (g *generator) typ(e ast.Expr) string {
	switch t := e.(type) {
	case *ast.Ident:
		m := map[string]string{"string": "String", "bool": "Boolean", "int": "Long", "uint": "Long", "byte": "Short", "rune": "Int", "int8": "Byte", "uint8": "Short", "int16": "Short", "uint16": "Int", "int32": "Int", "uint32": "Long", "int64": "Long", "uint64": "Long", "float32": "Float", "float64": "Double"}
		if v, ok := m[t.Name]; ok {
			return v
		}
		return t.Name
	case *ast.SelectorExpr:
		return "Instant"
	case *ast.StarExpr:
		return "Option[" + g.typ(t.X) + "]"
	case *ast.ArrayType:
		if isByte(t.Elt) {
			return "Array[Byte]"
		}
		return "Seq[" + g.typ(t.Elt) + "]"
	case *ast.MapType:
		return "Map[" + g.typ(t.Key) + ", " + g.typ(t.Value) + "]"
	}
	return "Any"
}
func (g *generator) def(e ast.Expr) string {
	switch t := e.(type) {
	case *ast.Ident:
		switch t.Name {
		case "string":
			return `""`
		case "bool":
			return "false"
		case "int8":
			return "0.toByte"
		case "int16", "byte", "uint8":
			return "0.toShort"
		case "int32", "rune", "uint16":
			return "0"
		case "float32":
			return "0f"
		case "float64":
			return "0d"
		case "int", "uint", "uint32", "int64", "uint64":
			return "0L"
		default:
			return t.Name + "()"
		}
	case *ast.SelectorExpr:
		return "Instant.EPOCH"
	case *ast.StarExpr:
		return "None"
	case *ast.ArrayType:
		if isByte(t.Elt) {
			if t.Len != nil {
				return "new Array[Byte](" + g.ExprToString(t.Len) + ")"
			}
			return "Array.emptyByteArray"
		}
		if t.Len != nil {
			return "Seq.fill(" + g.ExprToString(t.Len) + ")(" + g.def(t.Elt) + ")"
		}
		return "Seq.empty"
	case *ast.MapType:
		return "Map.empty"
	}
	return "null"
}
func (g *generator) codec(e ast.Expr) string {
	switch t := e.(type) {
	case *ast.Ident:
		if _, ok := g.TypeSpecs[t.Name]; ok {
			return t.Name + ".codec"
		}
		switch t.Name {
		case "int":
			return "BencGenerated.signed"
		case "uint":
			return "BencGenerated.unsigned"
		case "byte", "uint8":
			return "BencGenerated.u8"
		case "uint16":
			return "BencGenerated.u16"
		case "uint32":
			return "BencGenerated.u32"
		}
		return "summon[Benc[" + g.typ(e) + "]]"
	case *ast.SelectorExpr:
		return "summon[Benc[Instant]]"
	case *ast.StarExpr:
		return "BencGenerated.option(" + g.codec(t.X) + ")"
	case *ast.ArrayType:
		if t.Len != nil {
			if isByte(t.Elt) {
				return "BencGenerated.fixedBytes(" + g.ExprToString(t.Len) + ")"
			}
			return "BencGenerated.fixed(" + g.ExprToString(t.Len) + ", " + g.codec(t.Elt) + ")"
		}
		if isByte(t.Elt) {
			return "summon[Benc[Array[Byte]]]"
		}
		return "BencGenerated.seq(" + g.codec(t.Elt) + ")"
	case *ast.MapType:
		return "BencGenerated.map(" + g.codec(t.Key) + ", " + g.codec(t.Value) + ")"
	}
	return "summon[Benc[Any]]"
}
