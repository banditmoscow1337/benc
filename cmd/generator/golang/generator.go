type generator struct {
	*common.Context
	buf bytes.Buffer
}

func New(ctx *common.Context) common.Generator {
	return &generator{Context: ctx}
}

func (g *generator) Generate() (err error) {
	if err = g.Context.Validate(); err != nil {
		return err
	}
	g.printf("// Code generated by benc generator; DO NOT EDIT.\n\n")
	g.printf("package %s\n\n", g.PkgName)
	g.printf("import (\n")
	if g.usesTimeType() {
		g.printf("\t\"time\"\n")
	}
	g.printf("\tbstd \"github.com/banditmoscow1337/benc/std/golang\"\n")
	g.printf(")\n\n")
	if g.usesTimeType() {
		g.printf("var _ time.Time\n\n")
	}
	if filepath.Ext(g.InputFile) != ".go" {
		for _, ts := range g.Types {
			if st, ok := ts.Type.(*ast.StructType); ok {
				g.printf("type %s struct {\n", ts.Name.Name)
				for _, f := range st.Fields.List {
					if g.ShouldIgnoreField(f) {
						continue
					}
					for _, n := range f.Names {
						g.printf("%s %s\n", n.Name, g.ExprToString(f.Type))
					}
				}
				g.printf("}\n\n")
			} else {
				g.printf("type %s %s\n\n", ts.Name.Name, g.ExprToString(ts.Type))
			}
		}
	}

	for _, ts := range g.Types {
		if err = g.generateGoMethods(ts); err != nil {
			err = fmt.Errorf("generating methods for %s: %w", ts.Name.Name, err)
			return
		}
	}

	return g.formatGo("benc")
}

func (g *generator) generateGoMethods(ts *ast.TypeSpec) error {
	switch ts.Type.(type) {
	case *ast.StructType:
		return g.generateGoStructMethods(ts)
	case *ast.MapType:
		return g.generateGoMapAliasMethods(ts)
	}
	return nil
}

func (g *generator) generateGoStructMethods(ts *ast.TypeSpec) error {
	name := ts.Name.Name
	receiver := "v"
	supportedFields := g.GetSupportedFields(ts)

	g.printf("func (%s *%s) Size() (s int) {\n", receiver, name)
	for _, field := range supportedFields {
		if g.IsUnsupportedType(field.Type) {
			continue
		}
		for _, fName := range field.Names {
			g.printf("\ts += %s\n", g.getGoSizeExpr(field.Type, fmt.Sprintf("%s.%s", receiver, fName.Name)))
		}
	}
	g.printf("\treturn\n}\n\n")

	g.printf("func (%s *%s) Marshal(tn int, b []byte) (n int) {\n\tn = tn\n", receiver, name)
	for _, field := range supportedFields {
		if g.IsUnsupportedType(field.Type) {
			continue
		}
		for _, fName := range field.Names {
			g.printf("\tn = %s\n", g.getGoMarshalExpr(field.Type, "n", "b", fmt.Sprintf("%s.%s", receiver, fName.Name)))
		}
	}
	g.printf("\treturn n\n}\n\n")

	g.printf("func (%s *%s) Unmarshal(tn int, b []byte) (n int, err error) {\n\tn = tn\n", receiver, name)
	for _, field := range supportedFields {
		if g.IsUnsupportedType(field.Type) {
			continue
		}
		for _, fName := range field.Names {
			g.printf("\tif %s; err != nil {\n\t\treturn\n\t}\n", g.getGoUnmarshalExpr(field.Type, "n", "b", fmt.Sprintf("%s.%s", receiver, fName.Name)))
		}
	}
	g.printf("\treturn\n}\n\n")
	return nil
}

func (g *generator) generateGoMapAliasMethods(ts *ast.TypeSpec) error {
	name := ts.Name.Name
	receiver := "v"
	mapType := ts.Type.(*ast.MapType)

	if g.IsUnsupportedType(mapType) {
		return nil
	}

	g.printf("func (%s *%s) Size() (s int) {\n", receiver, name)
	g.printf("\ts += %s\n", g.getGoSizeExpr(mapType, "(*"+receiver+")"))
	g.printf("\treturn\n}\n\n")

	g.printf("func (%s *%s) Marshal(tn int, b []byte) (n int) {\n\tn = tn\n", receiver, name)
	g.printf("\tn = %s\n", g.getGoMarshalExpr(mapType, "n", "b", "(*"+receiver+")"))
	g.printf("\treturn\n}\n\n")

	g.printf("func (%s *%s) Unmarshal(tn int, b []byte) (n int, err error) {\n\tn = tn\n", receiver, name)
	g.printf("\tif %s; err != nil {\n\t\treturn\n\t}\n", g.getGoUnmarshalExpr(mapType, "n", "b", "(*"+receiver+")"))
	g.printf("\treturn\n}\n\n")
	return nil
}

func (g *generator) Tests() (err error) {
	g.printf("// Code generated by benc generator; DO NOT EDIT.\n\n")
	g.printf("package %s\n\n", g.PkgName)
	g.printf("import (\n")
	g.printf("\t\"math/rand\"\n")
	g.printf("\t\"testing\"\n")
	g.printf("\t\"time\"\n\n")
	g.printf("\tbtst \"github.com/banditmoscow1337/benc/std/golang\"\n")
	g.printf(")\n\n")

	for _, ts := range g.Types {
		g.generateGoTestGenerator(ts)
		g.generateGoTestComparer(ts)
	}

	var topLevelStruct *ast.TypeSpec
	for _, ts := range g.Types {
		if _, ok := ts.Type.(*ast.StructType); ok {
			if topLevelStruct == nil {
				topLevelStruct = ts
			}
		}
	}
	if topLevelStruct != nil {
		g.generateGoTestMain(topLevelStruct)
	}

	return g.formatGo("benc_test")
}

func (g *generator) generateGoTestGenerator(ts *ast.TypeSpec) {
	name := ts.Name.Name
	g.printf("func Generate%s(r *rand.Rand, depth int) %s {\n", name, name)
	g.printf("\tif depth <= 0 { return *new(%s) }\n", name)
	switch t := ts.Type.(type) {
	case *ast.StructType:
		g.printf("\treturn %s{\n", name)
		for _, field := range t.Fields.List {
			if g.ShouldIgnoreField(field) || g.IsUnsupportedType(field.Type) {
				continue
			}
			for _, fName := range field.Names {
				g.printf("\t\t%s: %s,\n", fName.Name, g.getGoTestGenerateExpr(field.Type, "r", "depth-1"))
			}
		}
		g.printf("\t}\n")
	case *ast.MapType, *ast.ArrayType:
		if g.IsUnsupportedType(ts.Type) {
			g.printf("\treturn nil\n")
		} else {
			g.printf("\treturn %s\n", g.getGoTestGenerateExpr(ts.Type, "r", "depth-1"))
		}
	default:
		g.printf("\treturn %s\n", g.getGoTestGenerateExpr(ts.Type, "r", "depth-1"))
	}
	g.printf("}\n\n")
}

func (g *generator) generateGoTestComparer(ts *ast.TypeSpec) {
	name := ts.Name.Name
	g.printf("func Compare%s(a, b %s) error {\n", name, name)
	switch t := ts.Type.(type) {
	case *ast.StructType:
		for _, field := range t.Fields.List {
			if g.ShouldIgnoreField(field) || g.IsUnsupportedType(field.Type) {
				continue
			}
			for _, fName := range field.Names {
				g.printf("\tif err := btst.CompareField(%q, %s); err != nil {\n\t\treturn err\n\t}\n", fName.Name, g.getGoTestCompareExpr(field.Type, "a."+fName.Name, "b."+fName.Name))
			}
		}
		g.printf("\treturn nil\n")
	default:
		if g.IsUnsupportedType(t) {
			g.printf("\treturn nil\n")
		} else {
			g.printf("\treturn %s\n", g.getGoTestCompareExpr(t, "a", "b"))
		}
	}
	g.printf("}\n\n")
}

func (g *generator) generateGoTestMain(ts *ast.TypeSpec) {
	name := ts.Name.Name
	g.printf("func Test%s(t *testing.T) {\n", name)
	g.printf("\tr := rand.New(rand.NewSource(time.Now().UnixNano()))\n")
	g.printf("\toriginal := Generate%s(r, btst.MaxDepth)\n\n", name)
	g.printf("\ts := original.Size()\n")
	g.printf("\tbuf := make([]byte, s)\n")
	g.printf("\tn := original.Marshal(0, buf)\n\n")
	g.printf("\tif n != s {\n")
	g.printf("\t\tt.Fatalf(\"Marshal size mismatch: expected %%d, got %%d\", s, n)\n")
	g.printf("\t}\n\n")
	g.printf("\tvar copy %s\n", name)
	g.printf("\tbytesRead, err := copy.Unmarshal(0, buf)\n")
	g.printf("\tif err != nil {\n")
	g.printf("\t\tt.Fatalf(\"Unmarshal failed: %%v\", err)\n")
	g.printf("\t}\n")
	g.printf("\tif bytesRead != s {\n")
	g.printf("\t\tt.Fatalf(\"Unmarshal bytes read mismatch: expected %%d, got %%d\", s, bytesRead)\n")
	g.printf("\t}\n\n")
	g.printf("\tif err := Compare%s(original, copy); err != nil {\n", name)
	g.printf("\t\tt.Fatalf(\"Comparison failed: %%v\\nOriginal: %%#v\\nCopy: %%#v\", err, original, copy)\n")
	g.printf("\t}\n")
	g.printf("}\n\n")
}

func (g *generator) printf(format string, args ...interface{}) {
	_, _ = fmt.Fprintf(&g.buf, format, args...)
}

func (g *generator) usesTimeType() bool {
	for _, ts := range g.Types {
		var types []ast.Expr
		switch t := ts.Type.(type) {
		case *ast.StructType:
			for _, field := range t.Fields.List {
				if !g.ShouldIgnoreField(field) && !g.IsUnsupportedType(field.Type) {
					types = append(types, field.Type)
				}
			}
		case *ast.MapType:
			if !g.IsUnsupportedType(t) {
				types = append(types, t)
			}
		}
		for _, expr := range types {
			found := false
			ast.Inspect(expr, func(n ast.Node) bool {
				if sel, ok := n.(*ast.SelectorExpr); ok && g.ExprToString(sel) == "time.Time" {
					found = true
					return false
				}
				return !found
			})
			if found {
				return true
			}
		}
	}
	return false
}

func (g *generator) formatGo(prefix string) (err error) {
	src, err := format.Source(g.buf.Bytes())
	if err != nil {
		log.Printf("---BEGIN FAILED SOURCE---\n%s\n---END FAILED SOURCE---", g.buf.String())
		return fmt.Errorf("failed to format generated code: %w", err)
	}

	g.buf.Reset()

	if _, err = g.buf.Write(src); err != nil {
		return
	}

	if err := g.WriteFile(&g.buf, prefix, "go"); err != nil {
		return err
	}

	g.buf.Reset()
	return nil
}

func (g *generator) getGoSizeExpr(expr ast.Expr, varName string) string {
	typeName := g.ExprToString(expr)
	if _, ok := g.TypeSpecs[typeName]; ok {
		return fmt.Sprintf("%s.Size()", varName)
	}

	switch t := expr.(type) {
	case *ast.Ident:
		info := g.getTypeInfo(t)
		sizer := "bstd.Size" + strings.Title(info.TypeName)
		if info.TypeName == "rune" {
			sizer = "bstd.SizeInt32"
		}
		if info.TypeName == "byte" {
			return sizer + "()"
		}
		return fmt.Sprintf("%s(%s)", sizer, varName)
	case *ast.StarExpr:
		return fmt.Sprintf("bstd.SizePointer(%s, %s)", varName, g.getGoSizeFunc(t.X, true))
	case *ast.SelectorExpr:
		if g.ExprToString(t) == "time.Time" {
			return "bstd.SizeTime()"
		}
		return fmt.Sprintf("%s.Size()", varName)
	case *ast.ArrayType:
		if t.Len != nil {
			lenStr := g.ExprToString(t.Len)
			eltInfo := g.getTypeInfo(t.Elt)
			if eltInfo.TypeName == "byte" {
				return fmt.Sprintf("bstd.SizeByteArray(%s)", lenStr)
			}
			return fmt.Sprintf("bstd.SizeArray(%s[:], %s)", varName, g.getGoSizeFunc(t.Elt, true))
		}

		eltInfo := g.getTypeInfo(t.Elt)
		if eltInfo.TypeName == "byte" {
			return fmt.Sprintf("bstd.SizeBytes(%s)", varName)
		}
		return fmt.Sprintf("bstd.SizeSlice(%s, %s)", varName, g.getGoSizeFunc(t.Elt, true))
	case *ast.MapType:
		return fmt.Sprintf("bstd.SizeMap(%s, %s, %s)", varName, g.getGoSizeFunc(t.Key, false), g.getGoSizeFunc(t.Value, false))
	default:
		return "0"
	}
}

func (g *generator) getGoSizeFunc(expr ast.Expr, typed bool) string {
	if _, ok := g.TypeSpecs[g.ExprToString(expr)]; !ok {
		switch t := expr.(type) {
		case *ast.Ident:
			name := g.getTypeInfo(t).TypeName
			if name == "rune" {
				return "bstd.SizeInt32"
			}
			if name != "byte" {
				return "bstd.Size" + strings.Title(name)
			}
			if !typed {
				return "bstd.SizeByte"
			}
		case *ast.SelectorExpr:
			_ = t
		}
	}
	return fmt.Sprintf("func(v %s) int { return %s }", g.ExprToString(expr), g.getGoSizeExpr(expr, "v"))
}

func (g *generator) getGoMarshalExpr(expr ast.Expr, n, buf, varName string) string {
	typeName := g.ExprToString(expr)
	if _, ok := g.TypeSpecs[typeName]; ok {
		return fmt.Sprintf("%s.Marshal(%s, %s)", varName, n, buf)
	}
	info := g.getTypeInfo(expr)
	switch t := expr.(type) {
	case *ast.Ident:
		return fmt.Sprintf("%s(%s, %s, %s)", info.Marshaler, n, buf, varName)
	case *ast.StarExpr:
		return fmt.Sprintf("bstd.MarshalPointer(%s, %s, %s, %s)", n, buf, varName, g.getGoMarshalFunc(t.X))
	case *ast.SelectorExpr:
		if g.ExprToString(t) == "time.Time" {
			return fmt.Sprintf("bstd.MarshalTime(%s, %s, %s)", n, buf, varName)
		}
		return fmt.Sprintf("%s.Marshal(%s, %s)", varName, n, buf)
	case *ast.ArrayType:
		if t.Len != nil {
			if g.getTypeInfo(t.Elt).TypeName == "byte" {
				return fmt.Sprintf("bstd.MarshalByteArray(%s, %s, %s[:])", n, buf, varName)
			}
			return fmt.Sprintf("bstd.MarshalArray(%s, %s, %s[:], %s)", n, buf, varName, g.getGoMarshalFunc(t.Elt))
		}

		eltInfo := g.getTypeInfo(t.Elt)
		if eltInfo.TypeName == "byte" {
			return fmt.Sprintf("bstd.MarshalBytes(%s, %s, %s)", n, buf, varName)
		}
		return fmt.Sprintf("bstd.MarshalSlice(%s, %s, %s, %s)", n, buf, varName, g.getGoMarshalFunc(t.Elt))
	case *ast.MapType:
		return fmt.Sprintf("bstd.MarshalMap(%s, %s, %s, %s, %s)", n, buf, varName, g.getGoMarshalFunc(t.Key), g.getGoMarshalFunc(t.Value))
	default:
		return n
	}
}

func (g *generator) getGoMarshalFunc(expr ast.Expr) string {
	if _, ok := g.TypeSpecs[g.ExprToString(expr)]; !ok {
		switch t := expr.(type) {
		case *ast.Ident:
			return g.getTypeInfo(t).Marshaler
		case *ast.SelectorExpr:
			if g.ExprToString(t) == "time.Time" {
				return "bstd.MarshalTime"
			}
		}
	}
	return fmt.Sprintf("func(n int, b []byte, v %s) int { return %s }", g.ExprToString(expr), g.getGoMarshalExpr(expr, "n", "b", "v"))
}

func (g *generator) getGoUnmarshalExpr(expr ast.Expr, n, buf, varName string) string {
	typeName := g.ExprToString(expr)
	if _, ok := g.TypeSpecs[typeName]; ok {
		return fmt.Sprintf("n, err = %s.Unmarshal(%s, %s)", varName, n, buf)
	}
	info := g.getTypeInfo(expr)
	switch t := expr.(type) {
	case *ast.Ident:
		return fmt.Sprintf("n, %s, err = %s(%s, %s)", varName, info.Unmarshaler, n, buf)
	case *ast.StarExpr:
		eltType := g.ExprToString(t.X)
		return fmt.Sprintf("n, %s, err = bstd.UnmarshalPointer[%s](%s, %s, %s)", varName, eltType, n, buf, g.getGoUnmarshalFunc(t.X))
	case *ast.SelectorExpr:
		if g.ExprToString(t) == "time.Time" {
			return fmt.Sprintf("n, %s, err = bstd.UnmarshalTime(%s, %s)", varName, n, buf)
		}
		return fmt.Sprintf("n, err = %s.Unmarshal(%s, %s)", varName, n, buf)
	case *ast.ArrayType:
		if t.Len != nil {
			eltInfo := g.getTypeInfo(t.Elt)
			if eltInfo.TypeName == "byte" {
				return fmt.Sprintf("n, err = bstd.UnmarshalByteArray(%s, %s, %s[:])", n, buf, varName)
			}
			return fmt.Sprintf("n, err = bstd.UnmarshalArray[%s](%s, %s, %s[:], %s)", eltInfo.TypeName, n, buf, varName, g.getGoUnmarshalFunc(t.Elt))
		}

		eltInfo := g.getTypeInfo(t.Elt)
		if eltInfo.TypeName == "byte" {
			return fmt.Sprintf("n, %s, err = bstd.UnmarshalBytesCopied(%s, %s)", varName, n, buf)
		}
		return fmt.Sprintf("n, %s, err = bstd.UnmarshalSlice[%s](%s, %s, %s)", varName, eltInfo.TypeName, n, buf, g.getGoUnmarshalFunc(t.Elt))
	case *ast.MapType:
		keyInfo := g.getTypeInfo(t.Key)
		valInfo := g.getTypeInfo(t.Value)
		return fmt.Sprintf("n, %s, err = bstd.UnmarshalMap[%s, %s](%s, %s, %s, %s)", varName, keyInfo.TypeName, valInfo.TypeName, n, buf, g.getGoUnmarshalFunc(t.Key), g.getGoUnmarshalFunc(t.Value))
	default:
		return fmt.Sprintf("n, %s, err = %s(%s, %s)", varName, info.Unmarshaler, n, buf)
	}
}

func (g *generator) getGoUnmarshalFunc(expr ast.Expr) string {
	if _, ok := g.TypeSpecs[g.ExprToString(expr)]; !ok {
		switch t := expr.(type) {
		case *ast.Ident:
			return g.getTypeInfo(t).Unmarshaler
		case *ast.SelectorExpr:
			if g.ExprToString(t) == "time.Time" {
				return "bstd.UnmarshalTime"
			}
		}
	}
	if _, ok := g.TypeSpecs[g.ExprToString(expr)]; ok {
		return fmt.Sprintf("func(n int, b []byte, v *%s) (int, error) { return v.Unmarshal(n, b) }", g.ExprToString(expr))
	}
	return fmt.Sprintf("func(n int, b []byte, v *%s) (int, error) { var err error; %s; return n, err }", g.ExprToString(expr), g.getGoUnmarshalExpr(expr, "n", "b", "(*v)"))
}

type typeGenInfo struct {
	TypeName    string
	Marshaler   string
	Unmarshaler string
}

func (g *generator) getTypeInfo(expr ast.Expr) typeGenInfo {
	typeName := g.ExprToString(expr)
	switch t := expr.(type) {
	case *ast.Ident:
		if _, ok := g.TypeSpecs[t.Name]; ok {
			return typeGenInfo{TypeName: t.Name}
		}
		title := strings.Title(t.Name)
		if t.Name == "byte" || t.Name == "uint8" {
			title, typeName = "Byte", "byte"
		} else if t.Name == "rune" {
			title, typeName = "Int32", "rune"
		}
		return typeGenInfo{
			TypeName:    typeName,
			Marshaler:   "bstd.Marshal" + title,
			Unmarshaler: "bstd.Unmarshal" + title,
		}
	default:
		return typeGenInfo{TypeName: typeName}
	}
}

func (g *generator) getGoTestGeneratorFunc(expr ast.Expr) string {
	if _, ok := g.TypeSpecs[g.ExprToString(expr)]; ok {
		return "Generate" + g.ExprToString(expr)
	}
	switch t := expr.(type) {
	case *ast.Ident:
		name := g.getTypeInfo(t).TypeName
		if name == "rune" {
			return "btst.GenerateInt32"
		}
		return "btst.Generate" + strings.Title(name)
	case *ast.SelectorExpr:
		if g.ExprToString(t) == "time.Time" {
			return "btst.GenerateTime"
		}
	case *ast.ArrayType:
		if t.Len != nil {
			name := g.ExprToString(expr)
			return fmt.Sprintf("func(r *rand.Rand, d int) %s { var v %s; for i := range v { v[i] = %s }; return v }", name, name, g.getGoTestGenerateExpr(t.Elt, "r", "d"))
		}
	}
	return fmt.Sprintf("func(r *rand.Rand, d int) %s { return %s }", g.ExprToString(expr), g.getGoTestGenerateExpr(expr, "r", "d"))
}

func (g *generator) getGoTestGenerateExpr(expr ast.Expr, r, d string) string {
	if _, ok := g.TypeSpecs[g.ExprToString(expr)]; ok {
		return fmt.Sprintf("Generate%s(%s, %s)", g.ExprToString(expr), r, d)
	}
	switch t := expr.(type) {
	case *ast.StarExpr:
		return fmt.Sprintf("btst.GeneratePointer(%s, %s, %s)", r, d, g.getGoTestGeneratorFunc(t.X))
	case *ast.ArrayType:
		if t.Len != nil {
			return fmt.Sprintf("(%s)(%s, %s)", g.getGoTestGeneratorFunc(expr), r, d)
		}
		return fmt.Sprintf("btst.GenerateSlice(%s, %s, %s)", r, d, g.getGoTestGeneratorFunc(t.Elt))
	case *ast.MapType:
		return fmt.Sprintf("btst.GenerateMap(%s, %s, %s, %s)", r, d, g.getGoTestGeneratorFunc(t.Key), g.getGoTestGeneratorFunc(t.Value))
	default:
		return fmt.Sprintf("%s(%s, %s)", g.getGoTestGeneratorFunc(expr), r, d)
	}
}

func (g *generator) getGoTestComparerFunc(expr ast.Expr) string {
	if _, ok := g.TypeSpecs[g.ExprToString(expr)]; ok {
		return "Compare" + g.ExprToString(expr)
	}
	switch t := expr.(type) {
	case *ast.SelectorExpr:
		if g.ExprToString(expr) == "time.Time" {
			return "btst.CompareTime"
		}
		return fmt.Sprintf("btst.ComparePrimitive[%s]", g.ExprToString(expr))
	case *ast.Ident:
		return fmt.Sprintf("btst.ComparePrimitive[%s]", g.ExprToString(expr))
	default:
		name := g.ExprToString(t)
		return fmt.Sprintf("func(a, b %s) error { return %s }", name, g.getGoTestCompareExpr(expr, "a", "b"))
	}
}

func (g *generator) getGoTestCompareExpr(expr ast.Expr, a, b string) string {
	if _, ok := g.TypeSpecs[g.ExprToString(expr)]; ok {
		return fmt.Sprintf("Compare%s(%s, %s)", g.ExprToString(expr), a, b)
	}
	switch t := expr.(type) {
	case *ast.SelectorExpr:
		if g.ExprToString(t) == "time.Time" {
			return fmt.Sprintf("btst.CompareTime(%s, %s)", a, b)
		}
		return fmt.Sprintf("btst.ComparePrimitive(%s, %s)", a, b)
	case *ast.StarExpr:
		return fmt.Sprintf("btst.ComparePointer(%s, %s, %s)", a, b, g.getGoTestComparerFunc(t.X))
	case *ast.ArrayType:
		if t.Len != nil {
			return fmt.Sprintf("btst.CompareSlice(%s[:], %s[:], %s)", a, b, g.getGoTestComparerFunc(t.Elt))
		}
		return fmt.Sprintf("btst.CompareSlice(%s, %s, %s)", a, b, g.getGoTestComparerFunc(t.Elt))
	case *ast.MapType:
		comparer := "btst.CompareMap"
		if _, ok := t.Key.(*ast.StarExpr); ok {
			comparer = "btst.ComparePointerKeyMap"
		}
		return fmt.Sprintf("%s(%s, %s, %s)", comparer, a, b, g.getGoTestComparerFunc(t.Value))
	default:
		return fmt.Sprintf("btst.ComparePrimitive(%s, %s)", a, b)
	}
}
