type generator struct {
	*common.Context
	out     bytes.Buffer
	support string
}

func New(ctx *common.Context) common.Generator {
	return &generator{Context: ctx, support: "BencSupport_" + regexp.MustCompile(`[^a-zA-Z0-9_]`).ReplaceAllString(ctx.BaseName, "_")}
}
func (g *generator) printf(pattern string, args ...any) { fmt.Fprintf(&g.out, pattern, args...) }

func (g *generator) Generate() error {
	if err := g.Validate(); err != nil {
		return err
	}
	g.out.Reset()
	g.printf("// Code generated by benc generator; DO NOT EDIT.\nimport java.util.*;\nimport java.math.BigInteger;\nimport java.time.Instant;\nimport main.com.benc.Bstd;\nimport main.com.benc.BencException;\nimport main.com.benc.BencBufferTooSmallException;\n\n")
	g.printf("class %s { // benc:internal\n", g.support)
	g.printf(`  static final BigInteger MAX_U64 = BigInteger.ONE.shiftLeft(64).subtract(BigInteger.ONE);
  static long bits(BigInteger v) {
    if (v.signum() < 0 || v.compareTo(MAX_U64) > 0) throw new IllegalArgumentException("unsigned value out of range");
    return v.longValue();
  }
  static BigInteger unsigned(long v) { return new BigInteger(Long.toUnsignedString(v)); }
  static Bstd.UnmarshalResult<Integer> u8(int n, byte[] b) throws BencException {
    var r = Bstd.unmarshalByte(n, b); return new Bstd.UnmarshalResult<>(r.newOffset(), r.value() & 255);
  }
  static Bstd.UnmarshalResult<Integer> u16(int n, byte[] b) throws BencException {
    var r = Bstd.unmarshalUint16(n, b); return new Bstd.UnmarshalResult<>(r.newOffset(), r.value() & 65535);
  }
  static Bstd.UnmarshalResult<Long> u32(int n, byte[] b) throws BencException {
    var r = Bstd.unmarshalUint32(n, b); return new Bstd.UnmarshalResult<>(r.newOffset(), Integer.toUnsignedLong(r.value()));
  }
  static Bstd.UnmarshalResult<BigInteger> u64(int n, byte[] b) throws BencException {
    var r = Bstd.unmarshalUint64(n, b); return new Bstd.UnmarshalResult<>(r.newOffset(), unsigned(r.value()));
  }
  static Bstd.UnmarshalResult<BigInteger> uintVar(int n, byte[] b) throws BencException {
    var r = Bstd.unmarshalUint(n, b); return new Bstd.UnmarshalResult<>(r.newOffset(), unsigned(r.value()));
  }
  static int sizeFixedBytes(byte[] v, int count) {
    if (v.length != count) throw new IllegalArgumentException("incorrect fixed array length"); return count;
  }
  static int writeFixedBytes(int n, byte[] b, byte[] v, int count) {
    sizeFixedBytes(v, count);
    if (n < 0 || n > b.length || count > b.length - n) throw new IndexOutOfBoundsException("fixed array exceeds buffer");
    System.arraycopy(v, 0, b, n, count); return n + count;
  }
  static Bstd.UnmarshalResult<byte[]> readFixedBytes(int n, byte[] b, int count) throws BencException {
    if (n < 0 || n > b.length || count > b.length - n) throw new BencBufferTooSmallException();
    return new Bstd.UnmarshalResult<>(n + count, Arrays.copyOfRange(b, n, n + count));
  }
  static <T> int sizeFixed(List<T> v, int count, java.util.function.Function<T,Integer> size) {
    if (v.size() != count) throw new IllegalArgumentException("incorrect fixed array length");
    int sum = 0; for (T item : v) sum += size.apply(item); return sum;
  }
  static <T> int writeFixed(int n, byte[] b, List<T> v, int count, Bstd.MarshalFunc<T> write) {
    if (v.size() != count) throw new IllegalArgumentException("incorrect fixed array length");
    for (T item : v) n = write.marshal(n, b, item); return n;
  }
  static <T> Bstd.UnmarshalResult<List<T>> readFixed(int n, byte[] b, int count, Bstd.UnmarshalFunc<T> read) throws BencException {
    List<T> result = new ArrayList<>(); for (int i = 0; i < count; i++) {
      var r = read.unmarshal(n, b); n = r.newOffset(); result.add(r.value());
    }
    return new Bstd.UnmarshalResult<>(n, result);
  }
}

`)
	for _, ts := range g.OrderedTypes() {
		name := ts.Name.Name
		if m, ok := ts.Type.(*ast.MapType); ok {
			g.printf("class %s { // benc:type %s\n", name, g.ExprToString(m))
			g.printf("  public Map<%s, %s> value = new HashMap<>();\n", g.javaType(m.Key), g.javaType(m.Value))
			g.printf("  public int size() { return %s; }\n", g.sizeExpr(m, "value"))
			g.printf("  public int marshal(int n, byte[] b) { return %s; }\n", g.writeExpr(m, "n", "b", "value"))
			g.printf("  public static Bstd.UnmarshalResult<%s> unmarshal(int n, byte[] b) throws BencException {\n    var r = %s;\n    var value = new %s(); value.value = r.value();\n    return new Bstd.UnmarshalResult<>(r.newOffset(), value);\n  }\n}\n\n", name, g.readExpr(m, "n", "b"), name)
			continue
		}
		g.printf("class %s {\n", name)
		for _, f := range g.GetSupportedFields(ts) {
			for _, id := range f.Names {
				g.printf("  public %s %s = %s; // %s\n", g.javaType(f.Type), id.Name, g.defaultExpr(f.Type), g.ExprToString(f.Type))
			}
		}
		g.printf("  public int size() { int size = 0;\n")
		for _, f := range g.GetSupportedFields(ts) {
			for _, id := range f.Names {
				g.printf("    size += %s;\n", g.sizeExpr(f.Type, "this."+id.Name))
			}
		}
		g.printf("    return size; }\n  public int marshal(int n, byte[] b) {\n")
		for _, f := range g.GetSupportedFields(ts) {
			for _, id := range f.Names {
				g.printf("    n = %s;\n", g.writeExpr(f.Type, "n", "b", "this."+id.Name))
			}
		}
		g.printf("    return n; }\n  public static Bstd.UnmarshalResult<%s> unmarshal(int n, byte[] b) throws BencException {\n    var value = new %s();\n", name, name)
		for _, f := range g.GetSupportedFields(ts) {
			for _, id := range f.Names {
				g.printf("    { var r = %s; n = r.newOffset(); value.%s = r.value(); }\n", g.readExpr(f.Type, "n", "b"), id.Name)
			}
		}
		g.printf("    return new Bstd.UnmarshalResult<>(n, value);\n  }\n}\n\n")
	}
	return g.WriteFile(&g.out, "_benc", "java")
}

func (g *generator) Tests() error {
	g.out.Reset()
	g.printf("// Code generated by benc generator; DO NOT EDIT.\nimport java.util.Arrays;\nclass BencGeneratedTest { public static void main(String[] args) throws Exception {\n")
	for _, ts := range g.Types {
		name := ts.Name.Name
		g.printf("  { var value = new %s(); byte[] wire = new byte[value.size()]; if (value.marshal(0, wire) != wire.length) throw new AssertionError(); var r = %s.unmarshal(0, wire); if (r.newOffset() != wire.length) throw new AssertionError(); byte[] again = new byte[r.value().size()]; if (r.value().marshal(0, again) != again.length || !Arrays.equals(wire, again)) throw new AssertionError(); }\n", name, name)
	}
	g.printf("} }\n")
	return g.WriteFile(&g.out, "_benc_test", "java")
}

func javaByte(e ast.Expr) bool {
	id, ok := e.(*ast.Ident)
	return ok && (id.Name == "byte" || id.Name == "uint8")
}
func (g *generator) javaType(e ast.Expr) string {
	switch t := e.(type) {
	case *ast.Ident:
		switch t.Name {
		case "string":
			return "String"
		case "bool":
			return "Boolean"
		case "int", "int64":
			return "Long"
		case "uint", "uint64":
			return "BigInteger"
		case "int8":
			return "Byte"
		case "byte", "uint8", "uint16", "int32", "rune":
			return "Integer"
		case "int16":
			return "Short"
		case "uint32":
			return "Long"
		case "float32":
			return "Float"
		case "float64":
			return "Double"
		default:
			return t.Name
		}
	case *ast.SelectorExpr:
		return "Instant"
	case *ast.StarExpr:
		return g.javaType(t.X)
	case *ast.ArrayType:
		if javaByte(t.Elt) {
			return "byte[]"
		}
		return "List<" + g.javaType(t.Elt) + ">"
	case *ast.MapType:
		return "Map<" + g.javaType(t.Key) + ", " + g.javaType(t.Value) + ">"
	}
	return "Object"
}
func (g *generator) defaultExpr(e ast.Expr) string {
	switch t := e.(type) {
	case *ast.Ident:
		switch t.Name {
		case "string":
			return `""`
		case "bool":
			return "false"
		case "uint", "uint64":
			return "BigInteger.ZERO"
		case "int", "int64", "uint32":
			return "0L"
		case "float32":
			return "0.0f"
		case "float64":
			return "0.0"
		case "int8":
			return "(byte)0"
		case "int16":
			return "(short)0"
		case "byte", "uint8", "uint16", "int32", "rune":
			return "0"
		default:
			return "new " + t.Name + "()"
		}
	case *ast.SelectorExpr:
		return "Instant.EPOCH"
	case *ast.StarExpr:
		return "null"
	case *ast.ArrayType:
		if javaByte(t.Elt) {
			if t.Len != nil {
				return "new byte[" + g.ExprToString(t.Len) + "]"
			}
			return "new byte[0]"
		}
		if t.Len != nil {
			return "new ArrayList<>(Collections.nCopies(" + g.ExprToString(t.Len) + ", " + g.defaultExpr(t.Elt) + "))"
		}
		return "new ArrayList<>()"
	case *ast.MapType:
		return "new HashMap<>()"
	}
	return "null"
}
func (g *generator) primitive(t *ast.Ident) string {
	switch t.Name {
	case "byte", "uint8":
		return "Byte"
	case "rune":
		return "Int32"
	default:
		return strings.ToUpper(t.Name[:1]) + t.Name[1:]
	}
}
func (g *generator) sizeExpr(e ast.Expr, v string) string {
	switch t := e.(type) {
	case *ast.Ident:
		if _, ok := g.TypeSpecs[t.Name]; ok {
			return v + ".size()"
		}
		if t.Name == "uint" {
			return fmt.Sprintf("Bstd.sizeUint(%s.bits(%s))", g.support, v)
		}
		if t.Name == "string" || t.Name == "int" {
			return fmt.Sprintf("Bstd.size%s(%s)", g.primitive(t), v)
		}
		return fmt.Sprintf("Bstd.size%s()", g.primitive(t))
	case *ast.SelectorExpr:
		return "Bstd.sizeTime()"
	case *ast.StarExpr:
		return fmt.Sprintf("Bstd.sizePointer(%s, v -> %s)", v, g.sizeExpr(t.X, "v"))
	case *ast.ArrayType:
		if t.Len != nil {
			if javaByte(t.Elt) {
				return fmt.Sprintf("%s.sizeFixedBytes(%s, %s)", g.support, v, g.ExprToString(t.Len))
			}
			return fmt.Sprintf("%s.sizeFixed(%s, %s, v -> %s)", g.support, v, g.ExprToString(t.Len), g.sizeExpr(t.Elt, "v"))
		}
		if javaByte(t.Elt) {
			return "Bstd.sizeBytes(" + v + ")"
		}
		return fmt.Sprintf("Bstd.sizeSlice(%s, v -> %s)", v, g.sizeExpr(t.Elt, "v"))
	case *ast.MapType:
		return fmt.Sprintf("Bstd.sizeMap(%s, k -> %s, v -> %s)", v, g.sizeExpr(t.Key, "k"), g.sizeExpr(t.Value, "v"))
	}
	return "0"
}
func (g *generator) writeExpr(e ast.Expr, n, b, v string) string {
	switch t := e.(type) {
	case *ast.Ident:
		if _, ok := g.TypeSpecs[t.Name]; ok {
			return fmt.Sprintf("%s.marshal(%s, %s)", v, n, b)
		}
		switch t.Name {
		case "uint":
			return fmt.Sprintf("Bstd.marshalUint(%s, %s, %s.bits(%s))", n, b, g.support, v)
		case "uint64":
			return fmt.Sprintf("Bstd.marshalUint64(%s, %s, %s.bits(%s))", n, b, g.support, v)
		case "byte", "uint8":
			return fmt.Sprintf("Bstd.marshalByte(%s, %s, (byte)(int)%s)", n, b, v)
		case "uint16":
			return fmt.Sprintf("Bstd.marshalUint16(%s, %s, (short)(int)%s)", n, b, v)
		case "uint32":
			return fmt.Sprintf("Bstd.marshalUint32(%s, %s, (int)(long)%s)", n, b, v)
		}
		return fmt.Sprintf("Bstd.marshal%s(%s, %s, %s)", g.primitive(t), n, b, v)
	case *ast.SelectorExpr:
		return fmt.Sprintf("Bstd.marshalTime(%s, %s, %s)", n, b, v)
	case *ast.StarExpr:
		return fmt.Sprintf("Bstd.marshalPointer(%s, %s, %s, (i,buf,v) -> %s)", n, b, v, g.writeExpr(t.X, "i", "buf", "v"))
	case *ast.ArrayType:
		if t.Len != nil {
			if javaByte(t.Elt) {
				return fmt.Sprintf("%s.writeFixedBytes(%s, %s, %s, %s)", g.support, n, b, v, g.ExprToString(t.Len))
			}
			return fmt.Sprintf("%s.writeFixed(%s, %s, %s, %s, (i,buf,v) -> %s)", g.support, n, b, v, g.ExprToString(t.Len), g.writeExpr(t.Elt, "i", "buf", "v"))
		}
		if javaByte(t.Elt) {
			return fmt.Sprintf("Bstd.marshalBytes(%s, %s, %s)", n, b, v)
		}
		return fmt.Sprintf("Bstd.marshalSlice(%s, %s, %s, (i,buf,v) -> %s)", n, b, v, g.writeExpr(t.Elt, "i", "buf", "v"))
	case *ast.MapType:
		return fmt.Sprintf("Bstd.marshalMap(%s, %s, %s, (i,buf,k) -> %s, (i,buf,v) -> %s)", n, b, v, g.writeExpr(t.Key, "i", "buf", "k"), g.writeExpr(t.Value, "i", "buf", "v"))
	}
	return n
}
func (g *generator) readExpr(e ast.Expr, n, b string) string {
	switch t := e.(type) {
	case *ast.Ident:
		if _, ok := g.TypeSpecs[t.Name]; ok {
			return fmt.Sprintf("%s.unmarshal(%s, %s)", t.Name, n, b)
		}
		switch t.Name {
		case "byte", "uint8":
			return fmt.Sprintf("%s.u8(%s, %s)", g.support, n, b)
		case "uint16":
			return fmt.Sprintf("%s.u16(%s, %s)", g.support, n, b)
		case "uint32":
			return fmt.Sprintf("%s.u32(%s, %s)", g.support, n, b)
		case "uint64":
			return fmt.Sprintf("%s.u64(%s, %s)", g.support, n, b)
		case "uint":
			return fmt.Sprintf("%s.uintVar(%s, %s)", g.support, n, b)
		}
		return fmt.Sprintf("Bstd.unmarshal%s(%s, %s)", g.primitive(t), n, b)
	case *ast.SelectorExpr:
		return fmt.Sprintf("Bstd.unmarshalTime(%s, %s)", n, b)
	case *ast.StarExpr:
		return fmt.Sprintf("Bstd.unmarshalPointer(%s, %s, (i,buf) -> %s)", n, b, g.readExpr(t.X, "i", "buf"))
	case *ast.ArrayType:
		if t.Len != nil {
			if javaByte(t.Elt) {
				return fmt.Sprintf("%s.readFixedBytes(%s, %s, %s)", g.support, n, b, g.ExprToString(t.Len))
			}
			return fmt.Sprintf("%s.readFixed(%s, %s, %s, (i,buf) -> %s)", g.support, n, b, g.ExprToString(t.Len), g.readExpr(t.Elt, "i", "buf"))
		}
		if javaByte(t.Elt) {
			return fmt.Sprintf("Bstd.unmarshalBytesCopied(%s, %s)", n, b)
		}
		return fmt.Sprintf("Bstd.unmarshalSlice(%s, %s, (i,buf) -> %s)", n, b, g.readExpr(t.Elt, "i", "buf"))
	case *ast.MapType:
		return fmt.Sprintf("Bstd.unmarshalMap(%s, %s, (i,buf) -> %s, (i,buf) -> %s)", n, b, g.readExpr(t.Key, "i", "buf"), g.readExpr(t.Value, "i", "buf"))
	}
	return "null"
}
