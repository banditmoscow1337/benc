package c

import (
	"bytes"
	"fmt"
	"github.com/banditmoscow1337/benc/cmd/generator/common"
	"go/ast"
	"strings"
)

type generator struct {
	*common.Context
	buf     bytes.Buffer
	ids     map[string]int
	exprs   []ast.Expr
	emitted int
}

func New(ctx *common.Context) *generator               { return &generator{Context: ctx, ids: map[string]int{}} }
func (g *generator) printf(format string, args ...any) { fmt.Fprintf(&g.buf, format, args...) }
func (g *generator) key(e ast.Expr) string             { return g.ExprToString(e) }
func (g *generator) id(e ast.Expr) int                 { return g.ids[g.key(e)] }
func (g *generator) cb(e ast.Expr, part string) string {
	return fmt.Sprintf("benc_generated_%s_%d", part, g.id(e))
}
func (g *generator) helper(e ast.Expr) string { return fmt.Sprintf("benc_generated_t%d", g.id(e)) }

func (g *generator) register(e ast.Expr) {
	switch t := e.(type) {
	case *ast.StarExpr:
		g.register(t.X)
	case *ast.ArrayType:
		g.register(t.Elt)
	case *ast.MapType:
		g.register(t.Key)
		g.register(t.Value)
	}
	key := g.key(e)
	if _, ok := g.ids[key]; !ok {
		g.ids[key] = len(g.exprs)
		g.exprs = append(g.exprs, e)
	}
}

func (g *generator) ctype(e ast.Expr) string {
	switch t := e.(type) {
	case *ast.Ident:
		if _, ok := g.TypeSpecs[t.Name]; ok {
			return t.Name
		}
		switch t.Name {
		case "bool":
			return "bool"
		case "byte", "uint8":
			return "uint8_t"
		case "rune", "int32":
			return "int32_t"
		case "int":
			return "intptr_t"
		case "uint":
			return "uintptr_t"
		case "int8", "int16", "int64", "uint16", "uint32", "uint64":
			return t.Name + "_t"
		case "float32":
			return "float"
		case "float64":
			return "double"
		}
	}
	return g.helper(e)
}

func (g *generator) def(e ast.Expr) {
	switch t := e.(type) {
	case *ast.Ident:
		if t.Name == "string" {
			g.printf("typedef struct { char* data; size_t data_len; } %s;\n", g.helper(e))
		}
	case *ast.SelectorExpr:
		g.printf("typedef struct { int64_t unix_nano; } %s;\n", g.helper(e))
	case *ast.StarExpr:
		g.printf("typedef struct { %s* item; } %s;\n", g.ctype(t.X), g.helper(e))
	case *ast.ArrayType:
		if t.Len != nil {
			g.printf("typedef struct { %s item[%s]; } %s;\n", g.ctype(t.Elt), g.ExprToString(t.Len), g.helper(e))
		} else {
			g.printf("typedef struct { %s* item; size_t item_count; } %s;\n", g.ctype(t.Elt), g.helper(e))
		}
	case *ast.MapType:
		g.printf("typedef struct { %s* item_keys; %s* item_values; size_t item_count; } %s;\n", g.ctype(t.Key), g.ctype(t.Value), g.helper(e))
	}
}

func (g *generator) fields(ts *ast.TypeSpec) []*ast.Field {
	if st, ok := ts.Type.(*ast.StructType); ok {
		return g.GetSupportedFields(&ast.TypeSpec{Type: st})
	}
	return []*ast.Field{{Names: []*ast.Ident{ast.NewIdent("benc_value")}, Type: ts.Type}}
}

func (g *generator) Generate() error {
	if err := g.Context.Validate(); err != nil {
		return err
	}
	g.ids = map[string]int{}
	g.exprs = nil
	g.emitted = 0
	g.buf.Reset()
	g.printf("// Code generated by benc generator; DO NOT EDIT.\n")
	guard := strings.Map(func(r rune) rune {
		if r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || r == '_' {
			return r
		}
		return '_'
	}, strings.ToUpper(g.BaseName))
	g.printf("#ifndef BENC_%s_H\n#define BENC_%s_H\n#include \"benc.h\"\n\n", guard, guard)
	for _, ts := range g.OrderedTypes() {
		for _, f := range g.fields(ts) {
			g.register(f.Type)
		}
		for ; g.emitted < len(g.exprs); g.emitted++ {
			g.def(g.exprs[g.emitted])
		}
		g.printf("typedef struct {\n")
		for _, f := range g.fields(ts) {
			for _, name := range f.Names {
				g.printf("  %s %s;\n", g.ctype(f.Type), name.Name)
			}
		}
		g.printf("} %s;\n\n", ts.Name.Name)
	}
	for _, ts := range g.Types {
		name := ts.Name.Name
		g.printf("size_t %s_size(const %s* v);\n", name, name)
		g.printf("bstd_status %s_marshal(uint8_t* buf,size_t len,size_t* off,const %s* v);\n", name, name)
		g.printf("bstd_status %s_unmarshal(const uint8_t* buf,size_t len,size_t* off,%s* v);\n", name, name)
		g.printf("void %s_free(%s* v);\n", name, name)
	}
	g.printf("#endif\n")
	if err := g.WriteFile(&g.buf, "_benc", "h"); err != nil {
		return err
	}
	g.printf("// Code generated by benc generator; DO NOT EDIT.\n#include \"%s_benc.h\"\n#include <stdlib.h>\n#include <string.h>\n\n", g.BaseName)
	for _, e := range g.exprs {
		ct := g.ctype(e)
		g.printf("static size_t %s(const void*);\n", g.cb(e, "size"))
		g.printf("static bstd_status %s(uint8_t*,size_t,size_t*,const void*);\n", g.cb(e, "marshal"))
		g.printf("static bstd_status %s(const uint8_t*,size_t,size_t*,void*);\n", g.cb(e, "unmarshal"))
		g.printf("static void %s(void*); // %s\n", g.cb(e, "free"), ct)
	}
	for _, e := range g.exprs {
		g.callback(e)
	}
	for _, ts := range g.Types {
		g.methods(ts)
	}
	return g.WriteFile(&g.buf, "_benc", "c")
}

func (g *generator) callback(e ast.Expr) {
	ct := g.ctype(e)
	g.printf("static size_t %s(const void* vp) { const %s* v=(const %s*)vp;\n", g.cb(e, "size"), ct, ct)
	switch t := e.(type) {
	case *ast.Ident:
		if _, ok := g.TypeSpecs[t.Name]; ok {
			g.printf("return %s_size(v);", t.Name)
		} else if t.Name == "string" {
			g.printf("return bstd_size_string(v->data,v->data_len);")
		} else if t.Name == "int" || t.Name == "uint" {
			g.printf("return bstd_size_%s(*v);", cBstdName(t.Name))
		} else {
			g.printf("(void)v; return bstd_size_%s();", cBstdName(t.Name))
		}
	case *ast.SelectorExpr:
		g.printf("(void)v; return bstd_size_time();")
	case *ast.StarExpr:
		g.printf("return bstd_size_pointer(v->item,%s);", g.cb(t.X, "size"))
	case *ast.ArrayType:
		if t.Len != nil {
			g.printf("size_t s=0; for(size_t i=0;i<%s;i++) s+=%s(&v->item[i]); return s;", g.ExprToString(t.Len), g.cb(t.Elt, "size"))
		} else if isByte(t.Elt) {
			g.printf("return bstd_size_bytes(v->item,v->item_count);")
		} else {
			g.printf("return bstd_size_slice(v->item,v->item_count,sizeof(*v->item),%s);", g.cb(t.Elt, "size"))
		}
	case *ast.MapType:
		g.printf("return bstd_size_map(v->item_keys,v->item_values,v->item_count,sizeof(*v->item_keys),sizeof(*v->item_values),%s,%s);", g.cb(t.Key, "size"), g.cb(t.Value, "size"))
	}
	g.printf("}\n")
	g.printf("static bstd_status %s(uint8_t* buf,size_t len,size_t* off,const void* vp) { const %s* v=(const %s*)vp;\n", g.cb(e, "marshal"), ct, ct)
	switch t := e.(type) {
	case *ast.Ident:
		if _, ok := g.TypeSpecs[t.Name]; ok {
			g.printf("return %s_marshal(buf,len,off,v);", t.Name)
		} else if t.Name == "string" {
			g.printf("return bstd_marshal_string(buf,len,off,v->data,v->data_len);")
		} else {
			g.printf("return bstd_marshal_%s(buf,len,off,*v);", cBstdName(t.Name))
		}
	case *ast.SelectorExpr:
		g.printf("return bstd_marshal_time(buf,len,off,v->unix_nano);")
	case *ast.StarExpr:
		g.printf("return bstd_marshal_pointer(buf,len,off,v->item,%s);", g.cb(t.X, "marshal"))
	case *ast.ArrayType:
		if t.Len != nil {
			g.printf("for(size_t i=0;i<%s;i++){ bstd_status s=%s(buf,len,off,&v->item[i]); if(s!=BSTD_OK)return s; } return BSTD_OK;", g.ExprToString(t.Len), g.cb(t.Elt, "marshal"))
		} else if isByte(t.Elt) {
			g.printf("return bstd_marshal_bytes(buf,len,off,v->item,v->item_count);")
		} else {
			g.printf("return bstd_marshal_slice(buf,len,off,v->item,v->item_count,sizeof(*v->item),%s);", g.cb(t.Elt, "marshal"))
		}
	case *ast.MapType:
		g.printf("return bstd_marshal_map(buf,len,off,v->item_keys,v->item_values,v->item_count,sizeof(*v->item_keys),sizeof(*v->item_values),%s,%s);", g.cb(t.Key, "marshal"), g.cb(t.Value, "marshal"))
	}
	g.printf("}\n")
	g.printf("static bstd_status %s(const uint8_t* buf,size_t len,size_t* off,void* vp) { %s* v=(%s*)vp;\n", g.cb(e, "unmarshal"), ct, ct)
	switch t := e.(type) {
	case *ast.Ident:
		if _, ok := g.TypeSpecs[t.Name]; ok {
			g.printf("return %s_unmarshal(buf,len,off,v);", t.Name)
		} else if t.Name == "string" {
			g.printf("uint8_t* data=NULL; size_t count=0; bstd_status s=bstd_unmarshal_bytes_alloc(buf,len,off,&data,&count); if(s==BSTD_OK){v->data=(char*)data;v->data_len=count;} return s;")
		} else {
			g.printf("return bstd_unmarshal_%s(buf,len,off,v);", cBstdName(t.Name))
		}
	case *ast.SelectorExpr:
		g.printf("return bstd_unmarshal_time(buf,len,off,&v->unix_nano);")
	case *ast.StarExpr:
		g.printf("return bstd_unmarshal_pointer_alloc_ex(buf,len,off,(void**)&v->item,sizeof(*v->item),%s,%s);", g.cb(t.X, "unmarshal"), g.cb(t.X, "free"))
	case *ast.ArrayType:
		if t.Len != nil {
			g.printf("for(size_t i=0;i<%s;i++){ bstd_status s=%s(buf,len,off,&v->item[i]); if(s!=BSTD_OK)return s; } return BSTD_OK;", g.ExprToString(t.Len), g.cb(t.Elt, "unmarshal"))
		} else if isByte(t.Elt) {
			g.printf("return bstd_unmarshal_bytes_alloc(buf,len,off,&v->item,&v->item_count);")
		} else {
			g.printf("return bstd_unmarshal_slice_alloc_ex(buf,len,off,(void**)&v->item,&v->item_count,sizeof(*v->item),%s,%s);", g.cb(t.Elt, "unmarshal"), g.cb(t.Elt, "free"))
		}
	case *ast.MapType:
		g.printf("return bstd_unmarshal_map_alloc_ex(buf,len,off,(void**)&v->item_keys,(void**)&v->item_values,&v->item_count,sizeof(*v->item_keys),sizeof(*v->item_values),%s,%s,%s,%s);", g.cb(t.Key, "unmarshal"), g.cb(t.Value, "unmarshal"), g.cb(t.Key, "free"), g.cb(t.Value, "free"))
	}
	g.printf("}\n")
	g.printf("static void %s(void* vp) { %s* v=(%s*)vp;\n", g.cb(e, "free"), ct, ct)
	switch t := e.(type) {
	case *ast.Ident:
		if _, ok := g.TypeSpecs[t.Name]; ok {
			g.printf("%s_free(v);", t.Name)
		} else if t.Name == "string" {
			g.printf("free(v->data); v->data=NULL; v->data_len=0;")
		} else {
			g.printf("(void)v;")
		}
	case *ast.SelectorExpr:
		g.printf("(void)v;")
	case *ast.StarExpr:
		g.printf("bstd_free_pointer(v->item,%s); v->item=NULL;", g.cb(t.X, "free"))
	case *ast.ArrayType:
		if t.Len != nil {
			g.printf("for(size_t i=0;i<%s;i++) %s(&v->item[i]);", g.ExprToString(t.Len), g.cb(t.Elt, "free"))
		} else {
			g.printf("bstd_free_slice(v->item,v->item_count,sizeof(*v->item),%s); v->item=NULL;v->item_count=0;", g.cb(t.Elt, "free"))
		}
	case *ast.MapType:
		g.printf("bstd_free_map(v->item_keys,v->item_values,v->item_count,sizeof(*v->item_keys),sizeof(*v->item_values),%s,%s); v->item_keys=NULL;v->item_values=NULL;v->item_count=0;", g.cb(t.Key, "free"), g.cb(t.Value, "free"))
	}
	g.printf("}\n\n")
}

func (g *generator) methods(ts *ast.TypeSpec) {
	name := ts.Name.Name
	fields := g.fields(ts)
	g.printf("size_t %s_size(const %s* v) { size_t s=0;\n", name, name)
	for _, f := range fields {
		for _, n := range f.Names {
			g.printf("s+=%s(&v->%s);\n", g.cb(f.Type, "size"), n.Name)
		}
	}
	g.printf("return s; }\n")
	g.printf("bstd_status %s_marshal(uint8_t* buf,size_t len,size_t* off,const %s* v) {\n", name, name)
	for _, f := range fields {
		for _, n := range f.Names {
			g.printf("{bstd_status s=%s(buf,len,off,&v->%s);if(s!=BSTD_OK)return s;}\n", g.cb(f.Type, "marshal"), n.Name)
		}
	}
	g.printf("return BSTD_OK; }\n")
	g.printf("bstd_status %s_unmarshal(const uint8_t* buf,size_t len,size_t* off,%s* v) { %s tmp={0};\n", name, name, name)
	for _, f := range fields {
		for _, n := range f.Names {
			g.printf("{bstd_status s=%s(buf,len,off,&tmp.%s);if(s!=BSTD_OK){%s_free(&tmp);return s;}}\n", g.cb(f.Type, "unmarshal"), n.Name, name)
		}
	}
	g.printf("*v=tmp;return BSTD_OK; }\n")
	g.printf("void %s_free(%s* v) {\n", name, name)
	for _, f := range fields {
		for _, n := range f.Names {
			g.printf("%s(&v->%s);\n", g.cb(f.Type, "free"), n.Name)
		}
	}
	g.printf("memset(v,0,sizeof(*v)); }\n\n")
}

func (g *generator) Tests() error {
	g.printf("// Code generated by benc generator; DO NOT EDIT.\n#include \"%s_benc.h\"\n#include <assert.h>\n#include <stdlib.h>\n#include <string.h>\nint main(void) {\n", g.BaseName)
	for _, ts := range g.Types {
		name := ts.Name.Name
		g.printf("{%s v={0}, copy={0}; size_t size=%s_size(&v);uint8_t* b=malloc(size?size:1);assert(b);size_t off=0;assert(%s_marshal(b,size,&off,&v)==BSTD_OK && off==size); off=0;assert(%s_unmarshal(b,size,&off,&copy)==BSTD_OK && off==size);size_t n=%s_size(&copy);assert(n==size);uint8_t* again=malloc(n?n:1);assert(again);off=0;assert(%s_marshal(again,n,&off,&copy)==BSTD_OK && off==n && memcmp(b,again,n)==0);%s_free(&copy);free(b);free(again);}\n", name, name, name, name, name, name, name)
	}
	g.printf("return 0;}\n")
	return g.WriteFile(&g.buf, "_benc_test", "c")
}

func cBstdName(goName string) string {
	switch goName {
	case "byte", "uint8":
		return "uint8"
	case "rune":
		return "int32"
	}
	return goName
}
func isByte(e ast.Expr) bool {
	id, ok := e.(*ast.Ident)
	return ok && (id.Name == "byte" || id.Name == "uint8")
}
