package typescript

import (
	"bytes"
	"fmt"
	"go/ast"
	"strings"

	"github.com/banditmoscow1337/benc/cmd/generator/common"
	"github.com/banditmoscow1337/benc/cmd/generator/javascript"
)

// TypeScript shares the executable JavaScript generator and wire runtime.
// The declaration below describes those same classes; it is not a second
// implementation or an intermediate schema.
type generator struct{ *common.Context }

func New(ctx *common.Context) common.Generator { return &generator{Context: ctx} }

func (g *generator) Generate() error {
	if err := javascript.New(g.Context).Generate(); err != nil {
		return err
	}
	var out bytes.Buffer
	fmt.Fprintln(&out, "// Code generated by benc generator; DO NOT EDIT.")
	fmt.Fprintln(&out, "import type { Time } from './std';")
	for _, ts := range g.Types {
		name := ts.Name.Name
		if m, ok := ts.Type.(*ast.MapType); ok {
			fmt.Fprintf(&out, "\n//benc:type %s\nexport declare class %s {\n", g.ExprToString(m), name)
			fmt.Fprintf(&out, "  value: Map<%s, %s>;\n", g.tsType(m.Key), g.tsType(m.Value))
			fmt.Fprintf(&out, "  constructor();\n  set(k: %s, v: %s): this;\n  get(k: %s): %s | undefined;\n", g.tsType(m.Key), g.tsType(m.Value), g.tsType(m.Key), g.tsType(m.Value))
		} else {
			fmt.Fprintf(&out, "\nexport declare class %s {\n  constructor();\n", name)
			for _, f := range g.GetSupportedFields(ts) {
				for _, id := range f.Names {
					fmt.Fprintf(&out, "  %s: %s; // %s\n", id.Name, g.tsType(f.Type), g.ExprToString(f.Type))
				}
			}
		}
		fmt.Fprintln(&out, "  size(): number;\n  marshal(n: number, b: Uint8Array): number;\n  unmarshal(n: number, b: Uint8Array): [number, this];\n}")
	}
	return g.WriteFile(&out, "_benc", "d.ts")
}

func (g *generator) Tests() error { return javascript.New(g.Context).Tests() }

func (g *generator) tsType(e ast.Expr) string {
	switch t := e.(type) {
	case *ast.Ident:
		switch t.Name {
		case "string":
			return "string"
		case "bool":
			return "boolean"
		case "int", "uint", "int64", "uint64":
			return "bigint"
		case "byte", "rune", "int8", "uint8", "int16", "uint16", "int32", "uint32", "float32", "float64":
			return "number"
		default:
			return t.Name
		}
	case *ast.StarExpr:
		return g.tsType(t.X) + " | null"
	case *ast.ArrayType:
		if id, ok := t.Elt.(*ast.Ident); ok && (id.Name == "byte" || id.Name == "uint8") {
			return "Uint8Array"
		}
		return "Array<" + g.tsType(t.Elt) + ">"
	case *ast.MapType:
		return fmt.Sprintf("Map<%s, %s>", g.tsType(t.Key), g.tsType(t.Value))
	case *ast.SelectorExpr:
		if g.ExprToString(e) == "time.Time" {
			return "Time"
		}
	}
	return strings.ReplaceAll(g.ExprToString(e), "*", "")
}
