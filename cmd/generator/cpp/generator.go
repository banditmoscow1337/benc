func (g *generator) Tests() error {
	g.printf("// Code generated by benc generator; DO NOT EDIT.\n")
	g.printf("#include \"%s_benc.hpp\"\n", g.BaseName)
	g.printf("#include <cassert>\n\n")

	g.printf("using namespace %s;\n\n", g.PkgName)
	g.printf("int main() {\n")
	for _, ts := range g.Types {
		name := ts.Name.Name
		g.printf("\t{ %s original{}; std::vector<std::byte> buf(original.Size());\n", name)
		g.printf("\t  assert(original.Marshal(buf,0)==buf.size());\n")
		g.printf("\t  %s copy{}; auto r=copy.Unmarshal(buf,0); assert(std::holds_alternative<std::size_t>(r) && std::get<std::size_t>(r)==buf.size());\n", name)
		g.printf("\t  std::vector<std::byte> again(copy.Size()); assert(copy.Marshal(again,0)==again.size() && again==buf); }\n")
	}
	g.printf("\treturn 0;\n")
	g.printf("}\n")

	return g.WriteFile(&g.buf, "_benc_test", "cpp")
}

