package python

import (
	"bytes"
	"fmt"
	"go/ast"
	"strings"

	"github.com/banditmoscow1337/benc/cmd/generator/common"
)

type generator struct {
	*common.Context
	out bytes.Buffer
}

func New(ctx *common.Context) common.Generator      { return &generator{Context: ctx} }
func (g *generator) printf(format string, a ...any) { fmt.Fprintf(&g.out, format, a...) }

func (g *generator) Generate() error {
	if err := g.Validate(); err != nil {
		return err
	}
	g.out.Reset()
	g.printf("# Code generated by benc generator; DO NOT EDIT.\nfrom __future__ import annotations\nfrom dataclasses import dataclass, field\nimport bstd\n\n")
	g.printf("def _size_fixed(value, count, sizer):\n    if len(value) != count: raise ValueError('incorrect fixed array length')\n    return sum(sizer(v) for v in value)\n\n")
	g.printf("def _write_fixed(n, b, value, count, writer):\n    if len(value) != count: raise ValueError('incorrect fixed array length')\n    for item in value: n = writer(n, b, item)\n    return n\n\n")
	g.printf("def _read_fixed(n, b, count, reader):\n    value = []\n    for _ in range(count):\n        n, item = reader(n, b)\n        value.append(item)\n    return n, value\n\n")
	g.printf("def _read_fixed_bytes(n, b, count):\n    if n < 0 or count < 0 or n > len(b) or count > len(b) - n: raise bstd.BencException(bstd.BencError.BUF_TOO_SMALL)\n    return n + count, bytes(b[n:n + count])\n\n")
	for _, ts := range g.OrderedTypes() {
		name := ts.Name.Name
		if m, ok := ts.Type.(*ast.MapType); ok {
			g.printf("class %s(dict[%s, %s]): # %s\n", name, g.pyType(m.Key), g.pyType(m.Value), g.ExprToString(m))
			g.printf("    def size(self): return %s\n", g.sizeExpr(m, "self"))
			g.printf("    def marshal(self, n, b): return %s\n", g.marshalExpr(m, "n", "b", "self"))
			g.printf("    @classmethod\n    def unmarshal(cls, n, b):\n        n, value = %s\n        return n, cls(value)\n\n", g.readExpr(m, "n", "b"))
			continue
		}
		g.printf("@dataclass\nclass %s:\n", name)
		for _, f := range g.GetSupportedFields(ts) {
			for _, id := range f.Names {
				g.printf("    %s: %s = %s # %s\n", id.Name, g.pyType(f.Type), g.defaultExpr(f.Type), g.ExprToString(f.Type))
			}
		}
		g.printf("\n    def size(self):\n        size = 0\n")
		for _, f := range g.GetSupportedFields(ts) {
			for _, id := range f.Names {
				g.printf("        size += %s\n", g.sizeExpr(f.Type, "self."+id.Name))
			}
		}
		g.printf("        return size\n\n    def marshal(self, n, b):\n")
		for _, f := range g.GetSupportedFields(ts) {
			for _, id := range f.Names {
				g.printf("        n = %s\n", g.marshalExpr(f.Type, "n", "b", "self."+id.Name))
			}
		}
		g.printf("        return n\n\n    @classmethod\n    def unmarshal(cls, n, b):\n        value = cls()\n")
		for _, f := range g.GetSupportedFields(ts) {
			for _, id := range f.Names {
				g.printf("        n, value.%s = %s\n", id.Name, g.readExpr(f.Type, "n", "b"))
			}
		}
		g.printf("        return n, value\n\n")
	}
	return g.WriteFile(&g.out, "_benc", "py")
}

func (g *generator) Tests() error {
	g.out.Reset()
	g.printf("# Code generated by benc generator; DO NOT EDIT.\nfrom %s_benc import %s\n\n", g.BaseName, g.allNames())
	for _, ts := range g.Types {
		name := ts.Name.Name
		g.printf("value = %s()\nwire = bytearray(value.size())\nassert value.marshal(0, wire) == len(wire)\nend, decoded = %s.unmarshal(0, wire)\nassert end == len(wire) and decoded == value\nagain = bytearray(decoded.size())\nassert decoded.marshal(0, again) == len(again) and again == wire\n", name, name)
	}
	return g.WriteFile(&g.out, "_benc_test", "py")
}

func (g *generator) allNames() string {
	names := make([]string, len(g.Types))
	for i, ts := range g.Types {
		names[i] = ts.Name.Name
	}
	return strings.Join(names, ", ")
}

func byteArray(e *ast.ArrayType) bool {
	id, ok := e.Elt.(*ast.Ident)
	return ok && (id.Name == "byte" || id.Name == "uint8")
}
func (g *generator) pyType(e ast.Expr) string {
	switch t := e.(type) {
	case *ast.Ident:
		switch t.Name {
		case "string":
			return "str"
		case "bool":
			return "bool"
		case "byte", "rune", "int", "uint", "int8", "uint8", "int16", "uint16", "int32", "uint32", "int64", "uint64":
			return "int"
		case "float32", "float64":
			return "float"
		default:
			return t.Name
		}
	case *ast.StarExpr:
		return g.pyType(t.X) + " | None"
	case *ast.ArrayType:
		if byteArray(t) {
			return "bytes"
		}
		return "list[" + g.pyType(t.Elt) + "]"
	case *ast.MapType:
		return "dict[" + g.pyType(t.Key) + ", " + g.pyType(t.Value) + "]"
	case *ast.SelectorExpr:
		return "int" // exact Unix nanoseconds
	}
	return "object"
}
func (g *generator) defaultExpr(e ast.Expr) string {
	switch t := e.(type) {
	case *ast.Ident:
		switch t.Name {
		case "string":
			return `""`
		case "bool":
			return "False"
		case "float32", "float64":
			return "0.0"
		case "byte", "rune", "int", "uint", "int8", "uint8", "int16", "uint16", "int32", "uint32", "int64", "uint64":
			return "0"
		default:
			return "field(default_factory=" + t.Name + ")"
		}
	case *ast.StarExpr:
		return "None"
	case *ast.ArrayType:
		if t.Len == nil {
			if byteArray(t) {
				return `b""`
			}
			return "field(default_factory=list)"
		}
		if byteArray(t) {
			return fmt.Sprintf("field(default_factory=lambda: bytes(%s))", g.ExprToString(t.Len))
		}
		return fmt.Sprintf("field(default_factory=lambda: [%s for _ in range(%s)])", g.defaultValue(t.Elt), g.ExprToString(t.Len))
	case *ast.MapType:
		return "field(default_factory=dict)"
	case *ast.SelectorExpr:
		return "0"
	}
	return "None"
}
func (g *generator) defaultValue(e ast.Expr) string {
	s := g.defaultExpr(e)
	if strings.HasPrefix(s, "field(default_factory=") {
		if id, ok := e.(*ast.Ident); ok {
			return id.Name + "()"
		}
		if _, ok := e.(*ast.MapType); ok {
			return "{}"
		}
		return "[]"
	}
	return s
}
func pyName(name string) string {
	switch name {
	case "byte", "uint8":
		return "byte"
	case "rune":
		return "int32"
	default:
		return name
	}
}
func (g *generator) sizeExpr(e ast.Expr, v string) string {
	switch t := e.(type) {
	case *ast.Ident:
		if _, ok := g.TypeSpecs[t.Name]; ok {
			return v + ".size()"
		}
		return fmt.Sprintf("bstd.size_%s(%s)", pyName(t.Name), v)
	case *ast.SelectorExpr:
		return "bstd.size_time()"
	case *ast.StarExpr:
		return fmt.Sprintf("bstd.size_optional(%s, lambda v: %s)", v, g.sizeExpr(t.X, "v"))
	case *ast.ArrayType:
		if t.Len != nil {
			return fmt.Sprintf("_size_fixed(%s, %s, lambda v: %s)", v, g.ExprToString(t.Len), g.sizeExpr(t.Elt, "v"))
		}
		if byteArray(t) {
			return "bstd.size_bytes(" + v + ")"
		}
		return fmt.Sprintf("bstd.size_slice(%s, lambda v: %s)", v, g.sizeExpr(t.Elt, "v"))
	case *ast.MapType:
		return fmt.Sprintf("bstd.size_map(%s, lambda v: %s, lambda v: %s)", v, g.sizeExpr(t.Key, "v"), g.sizeExpr(t.Value, "v"))
	}
	return "0"
}
func (g *generator) marshalExpr(e ast.Expr, n, b, v string) string {
	switch t := e.(type) {
	case *ast.Ident:
		if _, ok := g.TypeSpecs[t.Name]; ok {
			return fmt.Sprintf("%s.marshal(%s, %s)", v, n, b)
		}
		return fmt.Sprintf("bstd.marshal_%s(%s, %s, %s)", pyName(t.Name), n, b, v)
	case *ast.SelectorExpr:
		return fmt.Sprintf("bstd.marshal_time_nanos(%s, %s, %s)", n, b, v)
	case *ast.StarExpr:
		return fmt.Sprintf("bstd.marshal_optional(%s, %s, %s, lambda n,b,v: %s)", n, b, v, g.marshalExpr(t.X, "n", "b", "v"))
	case *ast.ArrayType:
		if t.Len != nil {
			return fmt.Sprintf("_write_fixed(%s, %s, %s, %s, lambda n,b,v: %s)", n, b, v, g.ExprToString(t.Len), g.marshalExpr(t.Elt, "n", "b", "v"))
		}
		if byteArray(t) {
			return fmt.Sprintf("bstd.marshal_bytes(%s, %s, %s)", n, b, v)
		}
		return fmt.Sprintf("bstd.marshal_slice(%s, %s, %s, lambda n,b,v: %s)", n, b, v, g.marshalExpr(t.Elt, "n", "b", "v"))
	case *ast.MapType:
		return fmt.Sprintf("bstd.marshal_map(%s, %s, %s, lambda n,b,v: %s, lambda n,b,v: %s)", n, b, v, g.marshalExpr(t.Key, "n", "b", "v"), g.marshalExpr(t.Value, "n", "b", "v"))
	}
	return n
}
func (g *generator) readExpr(e ast.Expr, n, b string) string {
	switch t := e.(type) {
	case *ast.Ident:
		if _, ok := g.TypeSpecs[t.Name]; ok {
			return fmt.Sprintf("%s.unmarshal(%s, %s)", t.Name, n, b)
		}
		return fmt.Sprintf("bstd.unmarshal_%s(%s, %s)", pyName(t.Name), n, b)
	case *ast.SelectorExpr:
		return fmt.Sprintf("bstd.unmarshal_time_nanos(%s, %s)", n, b)
	case *ast.StarExpr:
		return fmt.Sprintf("bstd.unmarshal_optional(%s, %s, lambda n,b: %s)", n, b, g.readExpr(t.X, "n", "b"))
	case *ast.ArrayType:
		if t.Len != nil {
			if byteArray(t) {
				return fmt.Sprintf("_read_fixed_bytes(%s, %s, %s)", n, b, g.ExprToString(t.Len))
			}
			return fmt.Sprintf("_read_fixed(%s, %s, %s, lambda n,b: %s)", n, b, g.ExprToString(t.Len), g.readExpr(t.Elt, "n", "b"))
		}
		if byteArray(t) {
			return fmt.Sprintf("bstd.unmarshal_bytes(%s, %s)", n, b)
		}
		return fmt.Sprintf("bstd.unmarshal_slice(%s, %s, lambda n,b: %s)", n, b, g.readExpr(t.Elt, "n", "b"))
	case *ast.MapType:
		return fmt.Sprintf("bstd.unmarshal_map(%s, %s, lambda n,b: %s, lambda n,b: %s)", n, b, g.readExpr(t.Key, "n", "b"), g.readExpr(t.Value, "n", "b"))
	}
	return "(n, None)"
}
