package kotlin

import (
	"bytes"
	"fmt"
	"go/ast"
	"strings"

	"github.com/banditmoscow1337/benc/cmd/generator/common"
)

type generator struct {
	*common.Context
	out bytes.Buffer
}

func New(ctx *common.Context) common.Generator          { return &generator{Context: ctx} }
func (g *generator) printf(pattern string, args ...any) { fmt.Fprintf(&g.out, pattern, args...) }

func (g *generator) Generate() error {
	if err := g.Validate(); err != nil {
		return err
	}
	g.out.Reset()
	g.printf(`// Code generated by benc generator; DO NOT EDIT.
import com.banditmoscow1337.bstd.Bstd
import java.time.Instant

private object BencFixed {
  fun sizeBytes(v: ByteArray, count: Int): Int { require(v.size == count); return count }
  fun writeBytes(b: ByteArray, n: Int, v: ByteArray, count: Int): Int {
    require(v.size == count); require(n >= 0 && n <= b.size && count <= b.size - n)
    v.copyInto(b, n); return n + count
  }
  fun readBytes(b: ByteArray, n: Int, count: Int): Pair<Int,ByteArray> {
    require(n >= 0 && n <= b.size && count <= b.size - n)
    return n + count to b.copyOfRange(n, n + count)
  }
  fun <T> size(v: List<T>, count: Int, fn: (T) -> Int): Int { require(v.size == count); return v.sumOf(fn) }
  fun <T> write(b: ByteArray, n: Int, v: List<T>, count: Int, fn: (ByteArray,Int,T) -> Int): Int {
    require(v.size == count); var p = n; for (item in v) p = fn(b,p,item); return p
  }
  fun <T> read(b: ByteArray, n: Int, count: Int, fn: (ByteArray,Int) -> Pair<Int,T>): Pair<Int,MutableList<T>> {
    val values = mutableListOf<T>(); var p = n
    repeat(count) { val (next,value) = fn(b,p); p = next; values.add(value) }
    return p to values
  }
}

`)
	for _, ts := range g.OrderedTypes() {
		name := ts.Name.Name
		if m, ok := ts.Type.(*ast.MapType); ok {
			g.printf("class %s { // benc:type %s\n", name, g.ExprToString(m))
			g.printf("  var value: MutableMap<%s, %s> = linkedMapOf()\n", g.typ(m.Key), g.typ(m.Value))
			g.printf("  fun size(): Int = %s\n", g.size(m, "value"))
			g.printf("  fun marshal(b: ByteArray, n: Int): Int = %s\n", g.write(m, "b", "n", "value"))
			g.printf("  companion object { fun unmarshal(b: ByteArray, n: Int): Pair<Int,%s> {\n    val (end,decoded) = %s\n    val result = %s(); result.value = decoded.toMutableMap(); return end to result\n  } }\n}\n\n", name, g.read(m, "b", "n"), name)
			continue
		}
		g.printf("class %s {\n", name)
		for _, f := range g.GetSupportedFields(ts) {
			for _, id := range f.Names {
				g.printf("  var %s: %s = %s // %s\n", id.Name, g.typ(f.Type), g.def(f.Type), g.ExprToString(f.Type))
			}
		}
		g.printf("  fun size(): Int { var size = 0\n")
		for _, f := range g.GetSupportedFields(ts) {
			for _, id := range f.Names {
				g.printf("    size += %s\n", g.size(f.Type, "this."+id.Name))
			}
		}
		g.printf("    return size\n  }\n  fun marshal(b: ByteArray, n: Int): Int { var p = n\n")
		for _, f := range g.GetSupportedFields(ts) {
			for _, id := range f.Names {
				g.printf("    p = %s\n", g.write(f.Type, "b", "p", "this."+id.Name))
			}
		}
		g.printf("    return p\n  }\n  companion object { fun unmarshal(b: ByteArray, n: Int): Pair<Int,%s> {\n    val value = %s(); var p = n\n", name, name)
		for _, f := range g.GetSupportedFields(ts) {
			for _, id := range f.Names {
				g.printf("    run { val r = %s; p = r.first; value.%s = r.second }\n", g.read(f.Type, "b", "p"), id.Name)
			}
		}
		g.printf("    return p to value\n  } }\n}\n\n")
	}
	return g.WriteFile(&g.out, "_benc", "kt")
}
func (g *generator) Tests() error {
	g.out.Reset()
	g.printf("// Code generated by benc generator; DO NOT EDIT.\nfun main() {\n")
	for _, ts := range g.Types {
		n := ts.Name.Name
		g.printf("  run { val value = %s(); val buffer = ByteArray(value.size()); check(value.marshal(buffer,0) == buffer.size); val (end,copy) = %s.unmarshal(buffer,0); check(end == buffer.size); val again = ByteArray(copy.size()); check(copy.marshal(again,0) == again.size && buffer.contentEquals(again)) }\n", n, n)
	}
	g.printf("}\n")
	return g.WriteFile(&g.out, "_benc_test", "kt")
}
func (g *generator) typ(e ast.Expr) string {
	switch t := e.(type) {
	case *ast.Ident:
		m := map[string]string{"string": "String", "bool": "Boolean", "int": "Long", "uint": "ULong", "byte": "UByte", "rune": "Int", "int8": "Byte", "uint8": "UByte", "int16": "Short", "uint16": "UShort", "int32": "Int", "uint32": "UInt", "int64": "Long", "uint64": "ULong", "float32": "Float", "float64": "Double"}
		if v, ok := m[t.Name]; ok {
			return v
		}
		return t.Name
	case *ast.SelectorExpr:
		return "Instant"
	case *ast.StarExpr:
		return g.typ(t.X) + "?"
	case *ast.ArrayType:
		if isByte(t.Elt) {
			return "ByteArray"
		}
		return "MutableList<" + g.typ(t.Elt) + ">"
	case *ast.MapType:
		return "MutableMap<" + g.typ(t.Key) + ", " + g.typ(t.Value) + ">"
	}
	return "Any"
}
func isByte(e ast.Expr) bool {
	t, ok := e.(*ast.Ident)
	return ok && (t.Name == "byte" || t.Name == "uint8")
}
func (g *generator) def(e ast.Expr) string {
	switch t := e.(type) {
	case *ast.Ident:
		switch t.Name {
		case "string":
			return `""`
		case "bool":
			return "false"
		case "int8":
			return "0"
		case "int16":
			return "0"
		case "uint8", "byte":
			return "0u"
		case "uint16":
			return "0u"
		case "int32", "rune":
			return "0"
		case "uint32":
			return "0u"
		case "int", "int64":
			return "0L"
		case "uint", "uint64":
			return "0uL"
		case "float32":
			return "0f"
		case "float64":
			return "0.0"
		default:
			return t.Name + "()"
		}
	case *ast.SelectorExpr:
		return "Instant.EPOCH"
	case *ast.StarExpr:
		return "null"
	case *ast.ArrayType:
		if isByte(t.Elt) {
			if t.Len != nil {
				return "ByteArray(" + g.ExprToString(t.Len) + ")"
			}
			return "byteArrayOf()"
		}
		if t.Len != nil {
			return "MutableList(" + g.ExprToString(t.Len) + ") { " + g.def(t.Elt) + " }"
		}
		return "mutableListOf()"
	case *ast.MapType:
		return "linkedMapOf()"
	}
	return "null"
}
func kotlinMethod(s string) string {
	if s == "bool" {
		return "Boolean"
	}
	if s == "byte" || s == "uint8" {
		return "Byte"
	}
	if s == "rune" {
		return "Int32"
	}
	if s == "int" {
		return "LongAsVarint"
	}
	if s == "uint" {
		return "ULongAsVarint"
	}
	if strings.HasPrefix(s, "uint") {
		return "UInt" + strings.TrimPrefix(s, "uint")
	}
	return strings.ToUpper(s[:1]) + s[1:]
}
func (g *generator) size(e ast.Expr, v string) string {
	switch t := e.(type) {
	case *ast.Ident:
		if _, ok := g.TypeSpecs[t.Name]; ok {
			return v + ".size()"
		}
		if t.Name == "string" || t.Name == "int" || t.Name == "uint" {
			return "Bstd.size" + kotlinMethod(t.Name) + "(" + v + ")"
		}
		return "Bstd.size" + kotlinMethod(t.Name) + "()"
	case *ast.SelectorExpr:
		return "Bstd.sizeTime()"
	case *ast.StarExpr:
		return "Bstd.sizePointer(" + v + ") { item -> " + g.size(t.X, "item") + " }"
	case *ast.ArrayType:
		if t.Len != nil {
			if isByte(t.Elt) {
				return "BencFixed.sizeBytes(" + v + ", " + g.ExprToString(t.Len) + ")"
			}
			return "BencFixed.size(" + v + ", " + g.ExprToString(t.Len) + ") { item -> " + g.size(t.Elt, "item") + " }"
		}
		if isByte(t.Elt) {
			return "Bstd.sizeBytes(" + v + ")"
		}
		return "Bstd.sizeSlice(" + v + ") { item -> " + g.size(t.Elt, "item") + " }"
	case *ast.MapType:
		return "Bstd.sizeMap(" + v + ", { item -> " + g.size(t.Key, "item") + " }, { item -> " + g.size(t.Value, "item") + " })"
	}
	return "0"
}
func (g *generator) write(e ast.Expr, b, n, v string) string {
	switch t := e.(type) {
	case *ast.Ident:
		if _, ok := g.TypeSpecs[t.Name]; ok {
			return v + ".marshal(" + b + ", " + n + ")"
		}
		if t.Name == "byte" || t.Name == "uint8" {
			v += ".toByte()"
		}
		return "Bstd.marshal" + kotlinMethod(t.Name) + "(" + b + ", " + n + ", " + v + ")"
	case *ast.SelectorExpr:
		return "Bstd.marshalTime(" + b + ", " + n + ", " + v + ")"
	case *ast.StarExpr:
		return "Bstd.marshalPointer(" + b + ", " + n + ", " + v + ") { buf, off, item -> " + g.write(t.X, "buf", "off", "item") + " }"
	case *ast.ArrayType:
		if t.Len != nil {
			if isByte(t.Elt) {
				return "BencFixed.writeBytes(" + b + ", " + n + ", " + v + ", " + g.ExprToString(t.Len) + ")"
			}
			return "BencFixed.write(" + b + ", " + n + ", " + v + ", " + g.ExprToString(t.Len) + ") { buf, off, item -> " + g.write(t.Elt, "buf", "off", "item") + " }"
		}
		if isByte(t.Elt) {
			return "Bstd.marshalBytes(" + b + ", " + n + ", " + v + ")"
		}
		return "Bstd.marshalSlice(" + b + ", " + n + ", " + v + ") { buf, off, item -> " + g.write(t.Elt, "buf", "off", "item") + " }"
	case *ast.MapType:
		return "Bstd.marshalMap(" + b + ", " + n + ", " + v + ", { buf, off, item -> " + g.write(t.Key, "buf", "off", "item") + " }, { buf, off, item -> " + g.write(t.Value, "buf", "off", "item") + " })"
	}
	return n
}
func (g *generator) read(e ast.Expr, b, n string) string {
	switch t := e.(type) {
	case *ast.Ident:
		if _, ok := g.TypeSpecs[t.Name]; ok {
			return t.Name + ".unmarshal(" + b + ", " + n + ")"
		}
		r := "Bstd.unmarshal" + kotlinMethod(t.Name) + "(" + b + ", " + n + ")"
		if t.Name == "byte" || t.Name == "uint8" {
			return r + ".let { it.first to it.second.toUByte() }"
		}
		return r
	case *ast.SelectorExpr:
		return "Bstd.unmarshalTime(" + b + ", " + n + ")"
	case *ast.StarExpr:
		return "Bstd.unmarshalPointer(" + b + ", " + n + ") { buf, off -> " + g.read(t.X, "buf", "off") + " }"
	case *ast.ArrayType:
		if t.Len != nil {
			if isByte(t.Elt) {
				return "BencFixed.readBytes(" + b + ", " + n + ", " + g.ExprToString(t.Len) + ")"
			}
			return "BencFixed.read(" + b + ", " + n + ", " + g.ExprToString(t.Len) + ") { buf, off -> " + g.read(t.Elt, "buf", "off") + " }"
		}
		if isByte(t.Elt) {
			return "Bstd.unmarshalBytes(" + b + ", " + n + ")"
		}
		return "Bstd.unmarshalSlice(" + b + ", " + n + ") { buf, off -> " + g.read(t.Elt, "buf", "off") + " }.let { it.first to it.second.toMutableList() }"
	case *ast.MapType:
		return "Bstd.unmarshalMap(" + b + ", " + n + ", { buf, off -> " + g.read(t.Key, "buf", "off") + " }, { buf, off -> " + g.read(t.Value, "buf", "off") + " }).let { it.first to it.second.toMutableMap() }"
	}
	return "null"
}
