type generator struct {
	*common.Context
	out bytes.Buffer
}

func New(ctx *common.Context) common.Generator    { return &generator{Context: ctx} }
func (g *generator) printf(s string, args ...any) { fmt.Fprintf(&g.out, s, args...) }

func (g *generator) Generate() error {
	if err := g.Validate(); err != nil {
		return err
	}
	g.out.Reset()
	g.printf(`// Code generated by benc generator; DO NOT EDIT.
import Foundation
import Bstd

private enum BencFixed {
  static func sizeBytes(_ v: [UInt8], count: Int) -> Int { precondition(v.count == count); return count }
  static func writeBytes(_ v: [UInt8], count: Int, at n: inout Int, into b: inout [UInt8]) throws {
    precondition(v.count == count); guard n >= 0 && n <= b.count && count <= b.count-n else { throw BstdError.bufferTooSmall }
    b.replaceSubrange(n..<(n+count), with: v); n += count
  }
  static func readBytes(count: Int, at n: inout Int, from b: [UInt8]) throws -> [UInt8] {
    guard n >= 0 && n <= b.count && count <= b.count-n else { throw BstdError.bufferTooSmall }
    defer { n += count }; return Array(b[n..<(n+count)])
  }
  static func size<T>(_ v: [T], count: Int, size: (T) -> Int) -> Int {
    precondition(v.count == count); return v.reduce(0) { $0 + size($1) }
  }
  static func write<T>(_ v: [T], count: Int, at n: inout Int, into b: inout [UInt8], write: (T, inout Int, inout [UInt8]) throws -> Void) throws {
    precondition(v.count == count); for item in v { try write(item, &n, &b) }
  }
  static func read<T>(count: Int, at n: inout Int, from b: [UInt8], read: (inout Int, [UInt8]) throws -> T) throws -> [T] {
    var values: [T] = []; for _ in 0..<count { values.append(try read(&n,b)) }; return values
  }
}

`)
	for _, ts := range g.OrderedTypes() {
		name := ts.Name.Name
		if m, ok := ts.Type.(*ast.MapType); ok {
			g.printf("public struct %s { // benc:type %s\n", name, g.ExprToString(m))
			g.printf("  public var value: %s = [:]\n", g.typ(m))
			g.printf("  public init() {}\n  public func size() -> Int { %s }\n", g.size(m, "value"))
			g.printf("  public func marshal(at n: inout Int, into b: inout [UInt8]) throws { %s }\n", g.write(m, "value", "n", "b"))
			g.printf("  public static func unmarshal(at n: inout Int, from b: [UInt8]) throws -> %s { var result = %s(); result.value = %s; return result }\n}\n\n", name, name, g.read(m, "n", "b"))
			continue
		}
		g.printf("public struct %s {\n", name)
		for _, f := range g.GetSupportedFields(ts) {
			for _, id := range f.Names {
				g.printf("  public var %s: %s = %s // %s\n", id.Name, g.typ(f.Type), g.def(f.Type), g.ExprToString(f.Type))
			}
		}
		g.printf("  public init() {}\n  public func size() -> Int {\n    var result = 0\n")
		for _, f := range g.GetSupportedFields(ts) {
			for _, id := range f.Names {
				g.printf("    result += %s\n", g.size(f.Type, "self."+id.Name))
			}
		}
		g.printf("    return result\n  }\n  public func marshal(at n: inout Int, into b: inout [UInt8]) throws {\n")
		for _, f := range g.GetSupportedFields(ts) {
			for _, id := range f.Names {
				g.printf("    %s\n", g.write(f.Type, "self."+id.Name, "n", "b"))
			}
		}
		g.printf("  }\n  public static func unmarshal(at n: inout Int, from b: [UInt8]) throws -> %s {\n    var result = %s()\n", name, name)
		for _, f := range g.GetSupportedFields(ts) {
			for _, id := range f.Names {
				g.printf("    result.%s = %s\n", id.Name, g.read(f.Type, "n", "b"))
			}
		}
		g.printf("    return result\n  }\n}\n\n")
	}
	return g.WriteFile(&g.out, "_benc", "swift")
}
func (g *generator) Tests() error {
	g.out.Reset()
	g.printf("// Code generated by benc generator; DO NOT EDIT.\nimport Foundation\nimport Bstd\n@main enum BencGeneratedTest { static func main() throws {\n")
	for _, ts := range g.Types {
		n := ts.Name.Name
		g.printf("  do { let value = %s(); var b = [UInt8](repeating: 0, count: value.size()); var offset = 0; try value.marshal(at: &offset, into: &b); precondition(offset == b.count); offset = 0; let copy = try %s.unmarshal(at: &offset, from: b); precondition(offset == b.count); var again = [UInt8](repeating: 0, count: copy.size()); offset = 0; try copy.marshal(at: &offset, into: &again); precondition(offset == again.count && again == b) }\n", n, n)
	}
	g.printf("} }\n")
	return g.WriteFile(&g.out, "_benc_test", "swift")
}
func isByte(e ast.Expr) bool {
	t, ok := e.(*ast.Ident)
	return ok && (t.Name == "byte" || t.Name == "uint8")
}
func (g *generator) typ(e ast.Expr) string {
	switch t := e.(type) {
	case *ast.Ident:
		m := map[string]string{"string": "String", "bool": "Bool", "int": "Int64", "uint": "UInt64", "byte": "UInt8", "rune": "Int32", "int8": "Int8", "uint8": "UInt8", "int16": "Int16", "uint16": "UInt16", "int32": "Int32", "uint32": "UInt32", "int64": "Int64", "uint64": "UInt64", "float32": "Float", "float64": "Double"}
		if v, ok := m[t.Name]; ok {
			return v
		}
		return t.Name
	case *ast.SelectorExpr:
		return "Int64" // exact nanoseconds
	case *ast.StarExpr:
		return g.typ(t.X) + "?"
	case *ast.ArrayType:
		return "[" + g.typ(t.Elt) + "]"
	case *ast.MapType:
		return "[" + g.typ(t.Key) + ": " + g.typ(t.Value) + "]"
	}
	return "Any"
}
func (g *generator) def(e ast.Expr) string {
	switch t := e.(type) {
	case *ast.Ident:
		switch t.Name {
		case "string":
			return `""`
		case "bool":
			return "false"
		case "float32", "float64", "int", "uint", "byte", "rune", "int8", "uint8", "int16", "uint16", "int32", "uint32", "int64", "uint64":
			return "0"
		default:
			return t.Name + "()"
		}
	case *ast.SelectorExpr:
		return "0"
	case *ast.StarExpr:
		return "nil"
	case *ast.ArrayType:
		if t.Len != nil {
			return "Array(repeating: " + g.def(t.Elt) + ", count: " + g.ExprToString(t.Len) + ")"
		}
		return "[]"
	case *ast.MapType:
		return "[:]"
	}
	return "[]"
}
func method(s string) string {
	switch s {
	case "byte", "uint8":
		return "Byte"
	case "rune":
		return "Int32"
	case "int":
		return "Int"
	case "uint":
		return "UInt"
	case "float32":
		return "Float32"
	case "float64":
		return "Float64"
	default:
		if strings.HasPrefix(s, "uint") {
			return "UInt" + strings.TrimPrefix(s, "uint")
		}
		return strings.ToUpper(s[:1]) + s[1:]
	}
}
func (g *generator) size(e ast.Expr, v string) string {
	switch t := e.(type) {
	case *ast.Ident:
		if _, ok := g.TypeSpecs[t.Name]; ok {
			return v + ".size()"
		}
		if t.Name == "int" || t.Name == "uint" || t.Name == "string" {
			return "Bstd.size" + method(t.Name) + "(" + v + ")"
		}
		return "Bstd.size" + method(t.Name) + "()"
	case *ast.SelectorExpr:
		return "Bstd.sizeTime()"
	case *ast.StarExpr:
		return "Bstd.sizePointer(" + v + ", sizer: { item in " + g.size(t.X, "item") + " })"
	case *ast.ArrayType:
		if t.Len != nil {
			if isByte(t.Elt) {
				return "BencFixed.sizeBytes(" + v + ", count: " + g.ExprToString(t.Len) + ")"
			}
			return "BencFixed.size(" + v + ", count: " + g.ExprToString(t.Len) + ", size: { item in " + g.size(t.Elt, "item") + " })"
		}
		if isByte(t.Elt) {
			return "Bstd.sizeBytes(" + v + ")"
		}
		return "Bstd.sizeSlice(" + v + ", sizer: { item in " + g.size(t.Elt, "item") + " })"
	case *ast.MapType:
		return "Bstd.sizeMap(" + v + ", kSizer: { item in " + g.size(t.Key, "item") + " }, vSizer: { item in " + g.size(t.Value, "item") + " })"
	}
	return "0"
}
func (g *generator) write(e ast.Expr, v, n, b string) string {
	switch t := e.(type) {
	case *ast.Ident:
		if _, ok := g.TypeSpecs[t.Name]; ok {
			return "try " + v + ".marshal(at: &" + n + ", into: &" + b + ")"
		}
		return "try Bstd.marshal" + method(t.Name) + "(" + v + ", at: &" + n + ", into: &" + b + ")"
	case *ast.SelectorExpr:
		return "try Bstd.marshalTimeNanos(" + v + ", at: &" + n + ", into: &" + b + ")"
	case *ast.StarExpr:
		return "try Bstd.marshalPointer(" + v + ", at: &" + n + ", into: &" + b + ", marshaler: { item, index, buffer in " + g.write(t.X, "item", "index", "buffer") + " })"
	case *ast.ArrayType:
		if t.Len != nil {
			if isByte(t.Elt) {
				return "try BencFixed.writeBytes(" + v + ", count: " + g.ExprToString(t.Len) + ", at: &" + n + ", into: &" + b + ")"
			}
			return "try BencFixed.write(" + v + ", count: " + g.ExprToString(t.Len) + ", at: &" + n + ", into: &" + b + ", write: { item, index, buffer in " + g.write(t.Elt, "item", "index", "buffer") + " })"
		}
		if isByte(t.Elt) {
			return "try Bstd.marshalBytes(" + v + ", at: &" + n + ", into: &" + b + ")"
		}
		return "try Bstd.marshalSlice(" + v + ", at: &" + n + ", into: &" + b + ", marshaler: { item, index, buffer in " + g.write(t.Elt, "item", "index", "buffer") + " })"
	case *ast.MapType:
		return "try Bstd.marshalMap(" + v + ", at: &" + n + ", into: &" + b + ", kMarshaler: { item, index, buffer in " + g.write(t.Key, "item", "index", "buffer") + " }, vMarshaler: { item, index, buffer in " + g.write(t.Value, "item", "index", "buffer") + " })"
	}
	return ""
}
func (g *generator) read(e ast.Expr, n, b string) string {
	switch t := e.(type) {
	case *ast.Ident:
		if _, ok := g.TypeSpecs[t.Name]; ok {
			return "try " + t.Name + ".unmarshal(at: &" + n + ", from: " + b + ")"
		}
		return "try Bstd.unmarshal" + method(t.Name) + "(at: &" + n + ", from: " + b + ")"
	case *ast.SelectorExpr:
		return "try Bstd.unmarshalTimeNanos(at: &" + n + ", from: " + b + ")"
	case *ast.StarExpr:
		return "try Bstd.unmarshalPointer(at: &" + n + ", from: " + b + ", unmarshaler: { index, buffer in " + g.read(t.X, "index", "buffer") + " })"
	case *ast.ArrayType:
		if t.Len != nil {
			if isByte(t.Elt) {
				return "try BencFixed.readBytes(count: " + g.ExprToString(t.Len) + ", at: &" + n + ", from: " + b + ")"
			}
			return "try BencFixed.read(count: " + g.ExprToString(t.Len) + ", at: &" + n + ", from: " + b + ", read: { index, buffer in " + g.read(t.Elt, "index", "buffer") + " })"
		}
		if isByte(t.Elt) {
			return "try Bstd.unmarshalBytes(at: &" + n + ", from: " + b + ")"
		}
		return "try Bstd.unmarshalSlice(at: &" + n + ", from: " + b + ", unmarshaler: { index, buffer in " + g.read(t.Elt, "index", "buffer") + " })"
	case *ast.MapType:
		return "try Bstd.unmarshalMap(at: &" + n + ", from: " + b + ", kUnmarshaler: { index, buffer in " + g.read(t.Key, "index", "buffer") + " }, vUnmarshaler: { index, buffer in " + g.read(t.Value, "index", "buffer") + " })"
	}
	return "0"
}
